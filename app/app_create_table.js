// app_create_table.js is embedded in the page of "vsql app" for a CREATE_TABLE
// tab (see create_table.v), after app_highlight.js. It builds the table name
// and columns from the payload, and the CREATE TABLE from them as they change.
// The payload is saved as it changes (see save), and posted with the form with
// the SQL, which Create table runs.

{
	const root = document.querySelector('.create-table');
	const form = root.closest('form');
	const state = JSON.parse(root.dataset.payload);
	const tbody = root.querySelector('table.columns tbody');
	const nameInput = root.querySelector('.table-name input');
	const createButton = root.querySelector('button.create');

	function toSql() {
		const lines = state.columns.map(column => '  ' + toName(column.name) + ' ' + column.type
			+ (column.auto_increment ? ' GENERATED BY DEFAULT AS IDENTITY' : column.default !== '' ? ' DEFAULT ' + column.default : '')
			+ (column.not_null ? ' NOT NULL' : ''));
		const key = state.columns.filter(column => column.primary_key).map(column => toName(column.name));
		if (key.length) lines.push('  PRIMARY KEY (' + key.join(', ') + ')');
		return 'CREATE TABLE ' + state.schema + '.' + toName(state.name) + ' (\n' + lines.join(',\n') + '\n)';
	}

	// save keeps the payload in VSQL_APP.TABS as it's changed (after a pause,
	// or when leaving the page), so the tab is the same when it's opened again.
	let saveTimer = null;
	const save = () => {
		clearTimeout(saveTimer);
		saveTimer = null;
		navigator.sendBeacon('/', new URLSearchParams({ tab: form.elements.namedItem('tab').value, payload: JSON.stringify(state) }));
	};
	window.addEventListener('pagehide', () => { if (saveTimer) save(); });

	// update shows the SQL, and sets what's posted. A table needs a name, and
	// each column a name and type.
	function update() {
		const sql = toSql();
		root.querySelector('pre.create-sql').innerHTML = toHtml(sql);
		const payload = JSON.stringify(state);
		if (payload !== form.elements.namedItem('payload').value) {
			clearTimeout(saveTimer);
			saveTimer = setTimeout(save, 300);
		}
		form.elements.namedItem('payload').value = payload;
		form.elements.namedItem('create_sql').value = sql;
		form.elements.namedItem('created_table').value = state.schema + '.' + toName(state.name);
		createButton.disabled = state.name.trim() === '' || state.columns.length === 0
			|| state.columns.some(column => column.name.trim() === '' || column.type.trim() === '');
	}

	const types = document.createElement('datalist');
	types.id = 'column-types';
	for (const type of ['INTEGER', 'BIGINT', 'SMALLINT', 'DECIMAL(10, 2)', 'REAL', 'DOUBLE PRECISION', 'BOOLEAN',
		'VARCHAR(255)', 'CHAR(10)', 'DATE', 'TIME', 'TIMESTAMP', 'TIMESTAMP WITH TIME ZONE']) types.append(new Option(type));
	root.append(types);

	// render builds a row for each column, the order is the order of the
	// columns in the table.
	function render() {
		tbody.textContent = '';
		state.columns.forEach((column, i) => {
			const text = (field, placeholder) => {
				const input = document.createElement('input');
				input.value = column[field];
				input.placeholder = placeholder;
				input.spellcheck = false;
				input.dataset.field = field;
				input.addEventListener('input', () => { column[field] = input.value; update(); });
				return input;
			};
			const check = field => {
				const input = document.createElement('input');
				input.type = 'checkbox';
				input.checked = column[field] || false;
				input.dataset.field = field;
				input.addEventListener('change', () => { column[field] = input.checked; update(); });
				return input;
			};
			// An auto increment column is an identity column, which can't
			// have a DEFAULT. A value can still be given for it. Only one
			// column can be auto increment.
			const defaultValue = text('default', 'DEFAULT');
			const autoIncrement = check('auto_increment');
			autoIncrement.title = 'GENERATED BY DEFAULT AS IDENTITY';
			defaultValue.disabled = autoIncrement.checked;
			// A table can only have one identity column.
			autoIncrement.addEventListener('change', () => {
				if (!autoIncrement.checked) return void (defaultValue.disabled = false);
				for (const other of state.columns) other.auto_increment = other === column;
				render();
			});
			const type = text('type', 'TYPE');
			type.setAttribute('list', 'column-types');
			const remove = document.createElement('button');
			remove.type = 'button';
			remove.className = 'remove';
			remove.title = 'Remove column';
			remove.textContent = '×';
			remove.addEventListener('click', () => { state.columns.splice(i, 1); render(); });
			const tr = tbody.insertRow();
			for (const element of [text('name', 'NAME'), type, check('not_null'), check('primary_key'), autoIncrement, defaultValue, remove]) {
				tr.insertCell().append(element);
			}
		});
		update();
	}

	nameInput.value = state.name;
	nameInput.addEventListener('input', () => { state.name = nameInput.value; update(); });
	root.querySelector('button.add-column').addEventListener('click', () => {
		state.columns.push({ name: '', type: 'VARCHAR(255)', not_null: false, primary_key: false, auto_increment: false, default: '' });
		render();
		tbody.querySelector('tr:last-child input').focus();
	});
	// Enter doesn't submit the form (which would go to the first tab).
	root.addEventListener('keydown', e => { if (e.key === 'Enter' && e.target.matches('input')) e.preventDefault(); });

	const discard = document.querySelector('dialog.discard');
	root.querySelector('button.cancel-create').addEventListener('click', () => discard.showModal());
	discard.querySelector('button.keep').addEventListener('click', () => discard.close());
	render();
}
