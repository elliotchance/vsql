module app

import json2
import vsql

// AppColumn is a column (after its ID) of a table in VSQL_APP.
struct AppColumn {
	table      string
	name       string
	definition string
}

// app_columns are the columns of each table in VSQL_APP, which is in every file.
// TABS has the type, title and payload of each tab of that file (and which tab
// is active) so they are restored the next time the file is opened. HISTORY has
// the SQL run in the tabs of that file (see history.v).
//
// A file keeps the tables and columns it had when it was last opened, so each
// table is created with just its ID, then each column that's missing is added
// in this order. A new table or column must be added to the end, and a NOT
// NULL column needs a DEFAULT for the rows that are already there.
const app_columns = [
	AppColumn{'TABS', 'TAB_TYPE', "VARCHAR(20) DEFAULT 'QUERY' NOT NULL"},
	AppColumn{'TABS', 'TITLE', "VARCHAR(50) DEFAULT 'New tab' NOT NULL"},
	AppColumn{'TABS', 'PAYLOAD', "VARCHAR(1000000) DEFAULT '{}' NOT NULL"},
	AppColumn{'TABS', 'ACTIVE', 'BOOLEAN DEFAULT FALSE NOT NULL'},
	AppColumn{'HISTORY', 'TAB_ID', 'INTEGER DEFAULT 0 NOT NULL'},
	AppColumn{'HISTORY', 'QUERY_TEXT', "VARCHAR(1000000) DEFAULT '' NOT NULL"},
	AppColumn{'HISTORY', 'ROW_COUNT', 'INTEGER'},
	AppColumn{'HISTORY', 'MESSAGE', 'VARCHAR(1000)'},
	AppColumn{'HISTORY', 'ERROR', 'VARCHAR(1000000)'},
	AppColumn{'HISTORY', 'RAN_AT', 'TIMESTAMP(0) WITHOUT TIME ZONE'},
]

// create_app_tables creates the schema, tables and columns in VSQL_APP of a file
// that are missing (see app_columns). A new table starts empty.
fn create_app_tables(db_file string, options vsql.ConnectionOptions) ! {
	mut conn := vsql.open_database(db_file, options)!
	defer {
		conn.close()
	}

	mut catalog := conn.catalog()
	if !catalog.schemas()!.any(it.name == 'VSQL_APP') {
		conn.query('CREATE SCHEMA vsql_app')!
	}
	mut tables := map[string]bool{}
	mut columns := map[string]bool{}
	for row in conn.query("SELECT table_name, column_name FROM INFORMATION_SCHEMA.COLUMNS WHERE table_schema = 'VSQL_APP'")! {
		tables[row.get_string('TABLE_NAME')!] = true
		columns['${row.get_string('TABLE_NAME')!}.${row.get_string('COLUMN_NAME')!}'] = true
	}

	for column in app_columns {
		if column.table !in tables {
			conn.query('CREATE TABLE vsql_app.${column.table} (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)')!
			tables[column.table] = true
		}
		if '${column.table}.${column.name}' !in columns {
			conn.query('ALTER TABLE vsql_app.${column.table} ADD COLUMN ${column.name} ${column.definition}')!
		}
	}
}

// no_tab is shown when there are no tabs, it has no SQL. The ids in
// VSQL_APP.TABS start at 1.
const no_tab = Tab{
	id:       0
	tab_type: query_tab
}

// query_tab is a tab with SQL to run.
const query_tab = 'QUERY'

// history_tab shows the queries of a file (see history.v). There's only one for
// each file. It has no payload.
const history_tab = 'HISTORY'

// create_table_tab is a tab to create a table, see create_table.v.
const create_table_tab = 'CREATE_TABLE'

// QueryPayload is the PAYLOAD (JSON) of a QUERY tab. Each tab type has its own
// payload.
struct QueryPayload {
	query_text string
	// params and param_types are the value and type of each "?" in query_text
	// (see Params).
	params      []string @[omitempty]
	param_types []string @[omitempty]
}

// Tab is a row of VSQL_APP.TABS in the file catalog, which is the file that its
// SQL runs in and its history is saved in.
struct Tab {
	id         int
	tab_type   string
	title      string
	query_text string
	active     bool
	params     Params
	// payload is the PAYLOAD as it's stored, for the other tab types.
	payload string
	catalog string
}

// ref identifies a tab in a form, since the ids are for each file.
fn (t Tab) ref() string {
	return '${t.catalog}:${t.id}'
}

// app_table is a table in VSQL_APP of a file.
fn app_table(catalog string, name string) string {
	return '"${catalog.replace('"', '""')}".vsql_app.${name}'
}

// tabs is the tabs of every file, in the order of the files.
fn (a &App) tabs(mut conn vsql.Connection) ![]Tab {
	mut tabs := []Tab{}
	for catalog in a.catalog_names {
		for row in conn.query('SELECT id, tab_type, title, payload, active FROM ${app_table(catalog, 'tabs')} ORDER BY id')! {
			tab_type := row.get_string('TAB_TYPE')!
			payload := row.get_string('PAYLOAD')!
			query := if tab_type == query_tab {
				json2.decode[QueryPayload](payload)!
			} else {
				QueryPayload{}
			}
			tabs << Tab{row.get_int('ID')!, tab_type, row.get_string('TITLE')!, query.query_text, row.get_bool('ACTIVE')! == .is_true, Params{query.params, query.param_types}, payload, catalog}
		}
	}

	return tabs
}

// add_tab adds a tab to a file after its others, makes it active and returns it.
fn (a &App) add_tab(mut conn vsql.Connection, catalog string, tab_type string, title string, payload string) !Tab {
	mut stmt := conn.prepare('INSERT INTO ${app_table(catalog, 'tabs')} (tab_type, title, payload, active) VALUES (?, ?, ?, FALSE)')!
	stmt.query({
		'?1': vsql.new_varchar_value(tab_type)
		'?2': vsql.new_varchar_value(tab_title(title))
		'?3': vsql.new_varchar_value(payload)
	})!
	mut tab := Tab{
		catalog: catalog
	}
	for row in conn.query('SELECT MAX(id) AS id FROM ${app_table(catalog, 'tabs')}')! {
		tab = Tab{
			...tab
			id: row.get_int('ID')!
		}
	}
	a.activate_tab(mut conn, tab)!

	return tab
}

fn (a &App) add_query_tab(mut conn vsql.Connection, catalog string, query_text string) !Tab {
	return a.add_tab(mut conn, catalog, query_tab, query_text, json2.encode(QueryPayload{ query_text: query_text }))
}

// show_history_tab makes the history tab of a file active, adding it if needed.
fn (a &App) show_history_tab(mut conn vsql.Connection, all_tabs []Tab, catalog string) ! {
	for t in all_tabs {
		if t.tab_type == history_tab && t.catalog == catalog {
			return a.activate_tab(mut conn, t)
		}
	}

	title := if a.catalog_names.len == 1 { 'Query History' } else { 'Query History (${catalog})' }
	a.add_tab(mut conn, catalog, history_tab, title, '{}')!
}

// activate_tab makes a tab active (there's one across all of the files), or no
// tab if it's no_tab.
fn (a &App) activate_tab(mut conn vsql.Connection, tab Tab) ! {
	for catalog in a.catalog_names {
		conn.query('UPDATE ${app_table(catalog, 'tabs')} SET active = FALSE WHERE active')!
	}
	if tab.id == no_tab.id {
		return
	}
	mut stmt := conn.prepare('UPDATE ${app_table(tab.catalog, 'tabs')} SET active = TRUE WHERE id = ?')!
	stmt.query({
		'?1': vsql.new_integer_value(tab.id)
	})!
}

// title_tab sets the title of a tab when it's run.
fn title_tab(mut conn vsql.Connection, tab Tab, query_text string) ! {
	mut stmt := conn.prepare('UPDATE ${app_table(tab.catalog, 'tabs')} SET title = ? WHERE id = ?')!
	stmt.query({
		'?1': vsql.new_varchar_value(tab_title(query_text))
		'?2': vsql.new_integer_value(tab.id)
	})!
}

fn save_tab(mut conn vsql.Connection, tab Tab, query_text string, params Params) ! {
	save_payload(mut conn, tab, json2.encode(QueryPayload{query_text, params.values, params.types}))!
}

fn save_payload(mut conn vsql.Connection, tab Tab, payload string) ! {
	mut stmt := conn.prepare('UPDATE ${app_table(tab.catalog, 'tabs')} SET payload = ? WHERE id = ?')!
	stmt.query({
		'?1': vsql.new_varchar_value(payload)
		'?2': vsql.new_integer_value(tab.id)
	})!
}

// remove_tab removes a tab and its history.
fn remove_tab(mut conn vsql.Connection, tab Tab) ! {
	mut stmt := conn.prepare('DELETE FROM ${app_table(tab.catalog, 'tabs')} WHERE id = ?')!
	stmt.query({
		'?1': vsql.new_integer_value(tab.id)
	})!
	remove_history(mut conn, tab.catalog, tab.id)!
}

// close_tab removes a tab and its last result. Closing the active tab activates
// the first tab, if there is one.
fn (a &App) close_tab(mut conn vsql.Connection, tab Tab, active Tab) ! {
	remove_tab(mut conn, tab)!
	lock a.results {
		a.results.delete(tab.ref())
	}
	if tab.ref() == active.ref() {
		a.activate_tab(mut conn, a.tabs(mut conn)![0] or { no_tab })!
	}
}
