# Altering a table from its menu, in an ALTER_TABLE tab: the ALTER TABLE
# statements are what's changed in the columns, and are run in a transaction.

import re
import time

import pytest
from playwright.sync_api import expect

from conftest import cli
from pages import AppPage

# people_sql is a table with an identity column (in the PRIMARY KEY), a NOT
# NULL column with a DEFAULT, a nullable column and a generated column.
people_sql = '''
CREATE TABLE people (id INT GENERATED BY DEFAULT AS IDENTITY, name VARCHAR(10) DEFAULT 'x' NOT NULL, age INT, g INT GENERATED ALWAYS AS (id * 2), PRIMARY KEY (id));
INSERT INTO people (name, age) VALUES ('a', 1);
'''


@pytest.fixture
def alter_ui(ui, db_file):
    """alter_ui is the page with an ALTER_TABLE tab for PEOPLE."""
    cli(db_file, people_sql)
    ui.reload()
    ui.table_menu('PEOPLE').get_by_role('button', name='Alter table').click()
    return ui


def alter_button(ui):
    return ui.page.locator('.alter-table').get_by_role('button', name='Alter table')


def test_alter_tab(alter_ui):
    # The tab has the columns as they are, and no changes. Only some fields of
    # a column that's already there can be changed.
    ui = alter_ui
    expect(ui.active_tab).to_have_text(re.compile(r'^Alter PEOPLE'))
    expect(ui.create_sql).to_have_text('-- No changes')
    expect(alter_button(ui)).to_be_disabled()
    expect(ui.columns).to_have_count(4)
    expect(ui.column(1, 'type')).to_have_value('CHARACTER VARYING(10)')
    expect(ui.column(1, 'default')).to_have_value("'x'")
    for field in ['name', 'type', 'auto_increment']:
        expect(ui.column(1, field)).to_be_disabled()
    expect(ui.column(0, 'auto_increment')).to_be_checked()
    expect(ui.column(0, 'default')).to_be_disabled()
    expect(ui.column(3, 'default')).to_be_disabled()

    # A NOT NULL can only be removed.
    expect(ui.column(1, 'not_null')).to_be_enabled()
    expect(ui.column(2, 'not_null')).to_be_disabled()

    # A new column can be anything, except auto increment (a table can only
    # have one identity column).
    ui.add_column()
    expect(ui.column(4, 'name')).to_be_enabled()
    expect(ui.column(4, 'type')).to_be_enabled()
    expect(ui.column(4, 'auto_increment')).to_be_disabled()


def test_alter(alter_ui, db_file):
    # Each change is an ALTER TABLE, in an order that works. Alter table runs
    # them, closes the tab and queries the table in a new tab.
    ui = alter_ui
    ui.column(1, 'not_null').uncheck()
    ui.column(1, 'default').fill("'y'")
    ui.columns.nth(2).get_by_role('button', name='×').click()
    ui.add_column()
    ui.column(3, 'name').fill('active')
    ui.column(3, 'type').fill('BOOLEAN')
    ui.column(3, 'default').fill('TRUE')
    ui.column(3, 'not_null').check()
    ui.column(3, 'primary_key').check()
    expect(ui.create_sql).to_have_text(
        'ALTER TABLE PUBLIC.PEOPLE DROP CONSTRAINT PEOPLE_PRIMARY_KEY; '
        'ALTER TABLE PUBLIC.PEOPLE DROP CONSTRAINT PEOPLE_NOT_NULL_2; '
        'ALTER TABLE PUBLIC.PEOPLE DROP COLUMN AGE; '
        "ALTER TABLE PUBLIC.PEOPLE ALTER COLUMN NAME SET DEFAULT 'y'; "
        'ALTER TABLE PUBLIC.PEOPLE ADD COLUMN ACTIVE BOOLEAN DEFAULT TRUE NOT NULL; '
        'ALTER TABLE PUBLIC.PEOPLE ADD PRIMARY KEY (ID, ACTIVE);')
    expect(ui.create_sql.locator('.kw').first).to_have_text('ALTER')

    alter_button(ui).click()
    expect(ui.tab_bar).to_have_count(1)
    expect(ui.editor).to_have_value('SELECT * FROM PUBLIC.PEOPLE')
    expect(ui.headers).to_have_text(['IDINTEGER', 'NAMECHARACTER VARYING(10)', 'GINTEGER', 'ACTIVEBOOLEAN'])
    expect(ui.rows.nth(0).locator('td')).to_have_text(['×', '1', 'a', '2', 'TRUE'])
    cli(db_file, 'INSERT INTO people (id) VALUES (5);')
    assert re.search(r'^ *5 \| y +\| +10 \| TRUE *$', cli(db_file, 'SELECT * FROM people WHERE id = 5;'), re.MULTILINE)


def test_drop_default(alter_ui):
    # An empty DEFAULT drops it.
    ui = alter_ui
    ui.column(1, 'default').fill('')
    expect(ui.create_sql).to_have_text('ALTER TABLE PUBLIC.PEOPLE ALTER COLUMN NAME DROP DEFAULT;')
    ui.column(1, 'default').fill("'x'")
    expect(ui.create_sql).to_have_text('-- No changes')


def test_alter_error(alter_ui, db_file):
    # If a statement fails, none of them are run, and the error is shown on
    # the tab.
    ui = alter_ui
    ui.add_column()
    ui.column(4, 'name').fill('d')
    ui.add_column()
    ui.column(5, 'name').fill('name')
    alter_button(ui).click()
    expect(ui.page.locator('.alter-table .error')).to_be_visible()
    expect(ui.columns).to_have_count(6)
    assert re.search(r'^ID +\| NAME +\| AGE +\| G$', cli(db_file, 'SELECT * FROM people;'), re.MULTILINE)


def test_alter_kept(alter_ui, db_file):
    # The changes are kept like any other tab, and Cancel closes the tab once
    # it's confirmed.
    ui = alter_ui
    ui.column(1, 'default').fill("'z'")
    deadline = time.monotonic() + 10
    while "'z'" not in cli(db_file, 'SELECT payload FROM vsql_app.tabs;'):
        assert time.monotonic() < deadline
        time.sleep(0.1)
    ui.reload()
    expect(ui.create_sql).to_have_text("ALTER TABLE PUBLIC.PEOPLE ALTER COLUMN NAME SET DEFAULT 'z';")

    ui.cancel_create()
    expect(ui.discard).to_contain_text('Discard these changes?')
    ui.discard.get_by_role('button', name='Discard').click()
    expect(ui.tab_bar).to_have_count(0)
    assert re.search(r"^'x'", cli(db_file, "SELECT column_default FROM information_schema.columns WHERE column_name = 'NAME';"), re.MULTILINE)
