# Adding a table to a schema from its menu, in a CREATE_TABLE tab: the CREATE
# TABLE is built from the table name and columns, and the tab is kept like any
# other tab.

import re
import time

from playwright.sync_api import expect

from conftest import cli
from pages import AppPage


def add_table(ui, schema='FOO'):
    ui.schema_menu('db', schema).get_by_role('button', name='Add table').click()


def wait_for(check):
    """wait_for waits (up to 10 seconds) for check() to be true."""
    deadline = time.monotonic() + 10
    while not check():
        assert time.monotonic() < deadline
        time.sleep(0.1)


def test_schema_menu(ui):
    # INFORMATION_SCHEMA and VSQL_APP don't have a menu.
    for schema in ['INFORMATION_SCHEMA', 'VSQL_APP']:
        expect(ui.page.locator('.schema-row').filter(has=ui.schema('db', schema))
               .locator(':scope > details.menu')).to_have_count(0)
    add_table(ui)
    expect(ui.active_tab).to_have_text(re.compile(r'^New table'))
    expect(ui.sidebar_tabs).to_have_text([re.compile('New table$')])


def test_sql(ui):
    # The SQL (which can't be edited) changes with the table name and columns.
    # It starts with an auto increment ID column as the PRIMARY KEY.
    add_table(ui)
    expect(ui.create_sql).to_have_text('CREATE TABLE FOO. ( ID INTEGER GENERATED BY DEFAULT AS IDENTITY, PRIMARY KEY (ID) )')
    expect(ui.page.locator('main textarea')).to_have_count(0)
    expect(ui.create_button).to_be_disabled()

    # In the SQL, a name is upper case (and quoted if it's a reserved word,
    # or has other characters) unless it's entered in double quotes, to keep
    # its case. What's entered isn't changed.
    ui.table_name.fill('people')
    expect(ui.table_name).to_have_value('people')
    ui.add_column()
    expect(ui.column(1, 'name')).to_be_focused()
    ui.column(1, 'name').fill('full name')
    ui.column(1, 'type').fill('VARCHAR(50)')
    ui.column(1, 'not_null').check()
    ui.column(1, 'default').fill("'x'")
    ui.add_column()
    ui.column(2, 'name').fill('order')
    ui.column(2, 'primary_key').check()
    ui.add_column()
    ui.column(3, 'name').fill('"Mixed"')
    expect(ui.create_sql).to_have_text('CREATE TABLE FOO.PEOPLE ( ID INTEGER GENERATED BY DEFAULT AS IDENTITY, "FULL NAME" VARCHAR(50) DEFAULT \'x\' NOT NULL, "ORDER" VARCHAR(255), "Mixed" VARCHAR(255), PRIMARY KEY (ID, "ORDER") )')
    expect(ui.column(2, 'name')).to_have_value('order')
    expect(ui.create_sql.locator('.kw').first).to_have_text('CREATE')
    expect(ui.create_button).to_be_enabled()

    # An auto increment column can't have a DEFAULT, and only one column can
    # be auto increment.
    ui.column(1, 'auto_increment').check()
    expect(ui.column(1, 'default')).to_be_disabled()
    expect(ui.column(0, 'auto_increment')).not_to_be_checked()
    expect(ui.create_sql).to_contain_text('ID INTEGER, "FULL NAME" VARCHAR(50) GENERATED BY DEFAULT AS IDENTITY NOT NULL,')
    ui.column(0, 'auto_increment').check()
    expect(ui.column(1, 'auto_increment')).not_to_be_checked()
    expect(ui.column(1, 'default')).to_be_enabled()
    expect(ui.create_sql).to_contain_text('"FULL NAME" VARCHAR(50) DEFAULT \'x\' NOT NULL,')

    # A column can be removed, and a column needs a name.
    ui.columns.nth(2).get_by_role('button', name='×').click()
    expect(ui.columns).to_have_count(3)
    expect(ui.create_sql).to_have_text('CREATE TABLE FOO.PEOPLE ( ID INTEGER GENERATED BY DEFAULT AS IDENTITY, "FULL NAME" VARCHAR(50) DEFAULT \'x\' NOT NULL, "Mixed" VARCHAR(255), PRIMARY KEY (ID) )')
    ui.column(1, 'name').fill('')
    expect(ui.create_button).to_be_disabled()


def test_create(ui, db_file):
    # Create table runs the SQL and closes the tab, then queries the table
    # (which is empty) in a new tab. ID is auto increment.
    add_table(ui)
    ui.table_name.fill('people')
    ui.add_column()
    ui.column(1, 'name').fill('name')
    ui.column(1, 'not_null').check()
    ui.create_button.click()
    expect(ui.tab_bar).to_have_count(1)
    expect(ui.active_tab).to_have_text(re.compile(r'^SELECT \* FROM FOO\.PEOPLE'))
    expect(ui.editor).to_have_value('SELECT * FROM FOO.PEOPLE')
    expect(ui.status).to_have_text(re.compile(r'^0 rows \('))
    expect(ui.headers).to_have_text(['IDINTEGER', 'NAMECHARACTER VARYING(255)'])
    expect(ui.sidebar_table('PEOPLE', schema='FOO')).to_have_count(1)
    cli(db_file, 'INSERT INTO foo.people (name) VALUES (\'a\');')
    assert re.search(r'^ *1 *\| a *$', cli(db_file, 'SELECT * FROM foo.people;'), re.MULTILINE)


def test_create_error(ui):
    # If it fails, the error is shown and the tab is kept.
    add_table(ui)
    ui.table_name.fill('bar')
    ui.create_button.click()
    expect(ui.page.locator('.create-table .error')).to_contain_text('duplicate table')
    expect(ui.table_name).to_have_value('bar')
    expect(ui.tab_bar).to_have_count(1)


def test_cancel(ui, db_file):
    # Cancel closes the tab once it's confirmed.
    add_table(ui)
    ui.table_name.fill('people')
    ui.cancel_create()
    expect(ui.discard).to_be_visible()
    ui.discard.get_by_role('button', name='Keep editing').click()
    expect(ui.discard).not_to_be_visible()
    expect(ui.table_name).to_have_value('people')

    ui.cancel_create()
    ui.discard.get_by_role('button', name='Discard').click()
    expect(ui.tab_bar).to_have_count(0)
    assert 'PEOPLE' not in cli(db_file, 'SELECT table_name FROM INFORMATION_SCHEMA.TABLES;')


def test_kept(page, db_file, start_app):
    # Everything that's entered is saved in VSQL_APP.TABS as it's changed, so
    # it's the same when the app is started again, or after going to another
    # tab.
    app = start_app(db_file)
    ui = AppPage(page, app)
    add_table(ui)
    ui.table_name.fill('people')
    ui.add_column()
    ui.column(1, 'name').fill('name')
    ui.column(1, 'type').fill('CHAR(5)')
    ui.column(1, 'not_null').check()
    ui.column(1, 'default').fill("'x'")
    sql = 'CREATE TABLE FOO.PEOPLE ( ID INTEGER GENERATED BY DEFAULT AS IDENTITY, NAME CHAR(5) DEFAULT \'x\' NOT NULL, PRIMARY KEY (ID) )'
    expect(ui.create_sql).to_have_text(sql)
    wait_for(lambda: 'CHAR(5)' in cli(db_file, 'SELECT payload FROM vsql_app.tabs;')
             and "'x'" in cli(db_file, 'SELECT payload FROM vsql_app.tabs;'))

    app.stop()
    ui.open(start_app(db_file))
    expect(ui.create_sql).to_have_text(sql)
    expect(ui.table_name).to_have_value('people')
    expect(ui.column(1, 'not_null')).to_be_checked()

    ui.new_tab()
    ui.tab('New table').click()
    expect(ui.create_sql).to_have_text(sql)
