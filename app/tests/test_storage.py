# The tabs are saved in VSQL_APP of the first file, so they are restored when
# it's opened again.

import re

from playwright.sync_api import expect

from conftest import cli, count
from pages import AppPage, titles


def test_restore_tabs(ui, db_file, start_app):
    # The tabs (and which is active) are restored when the file is opened
    # again, but not their results. Every tab is a QUERY tab, the only tab type
    # so far, and its PAYLOAD is JSON with its SQL.
    ui.sidebar_table('my <t>').click()
    ui.new_tab()
    ui.run('INSERT INTO foo.bar (y) VALUES (TRUE)')
    ui.tab('SELECT * FROM PUBLIC."my <t>"').click()
    ui.run('SELECT * FROM nope')
    ui.app.stop()

    assert count(db_file, "SELECT COUNT(*) FROM vsql_app.tabs WHERE tab_type = 'QUERY';") == 2
    assert '{"query_text":"SELECT * FROM nope"}' in cli(db_file, 'SELECT payload FROM vsql_app.tabs WHERE id = 1;')

    ui.open(start_app(db_file))
    expect(ui.tab_bar).to_have_text(['SELECT * FROM nope×', 'INSERT INTO foo.bar (y) VALUES...×'])
    expect(ui.active_tab).to_have_text('SELECT * FROM nope×')
    expect(ui.empty).to_have_text('Run to see the result.')


def test_default_file(page, tmp_path, start_app):
    # Without a file, app.vsql in the current directory is created (or opened).
    ui = AppPage(page, start_app(cwd=tmp_path))
    expect(ui.sections).to_have_text([re.compile('app$'), re.compile('Tabs 0$')])
    ui.new_tab()
    ui.app.stop()
    assert count(tmp_path / 'app.vsql', 'SELECT COUNT(*) FROM vsql_app.tabs;') == 1

    ui.open(start_app(cwd=tmp_path))
    expect(ui.tab_bar).to_have_count(1)


def test_old_file(page, make_file, start_app):
    # A file keeps the VSQL_APP tables and columns it had, so the missing
    # columns are added (with their DEFAULT for the rows already there).
    old_file = make_file('old.vsql', '''
        CREATE SCHEMA vsql_app;
        CREATE TABLE vsql_app.tabs (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(50) NOT NULL);
        INSERT INTO vsql_app.tabs (title) VALUES ('old tab');
    ''')
    ui = AppPage(page, start_app(old_file))
    expect(ui.sidebar_tabs).to_have_text(titles('old tab'))
    ui.app.stop()
    assert re.search(r'QUERY +\| +\{\} +\| +FALSE', cli(old_file, 'SELECT tab_type, payload, active FROM vsql_app.tabs;'))
