CREATE TABLE foo.parent (
  id INT NOT NULL,
  name VARCHAR(20) DEFAULT 'it''s',
  note VARCHAR(20) DEFAULT 'a\b',
  CONSTRAINT parent_pk PRIMARY KEY (id),
  CONSTRAINT uq1 UNIQUE (name),
  UNIQUE (note) DEFERRABLE
);
CREATE TABLE foo.child (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pid INT DEFAULT 1,
  "Mixed Case" VARCHAR(20),
  "order" INT CHECK ("order" > 0),
  CONSTRAINT fk1 FOREIGN KEY (pid) REFERENCES foo.parent (id) ON DELETE CASCADE,
  CONSTRAINT fk2 FOREIGN KEY (pid) REFERENCES foo.parent (id) ON UPDATE SET DEFAULT ON DELETE SET DEFAULT DEFERRABLE
);
CREATE TABLE types (
  i INT GENERATED ALWAYS AS IDENTITY,
  b BOOLEAN DEFAULT TRUE,
  si SMALLINT DEFAULT NULL,
  bi BIGINT,
  r REAL,
  d DOUBLE PRECISION,
  c CHAR(5),
  c2 CHAR(300),
  c2_more VARCHAR(600),
  vc VARCHAR(10),
  lv VARCHAR(5000),
  de DECIMAL(10, 2),
  n NUMERIC,
  dt DATE DEFAULT CURRENT_DATE,
  t TIME DEFAULT LOCALTIME,
  tz TIME(3) WITH TIME ZONE,
  ts TIMESTAMP(3) DEFAULT LOCALTIMESTAMP(3),
  tstz TIMESTAMP(6) WITH TIME ZONE,
  g INT GENERATED ALWAYS AS (si + 1),
  g2 INT GENERATED ALWAYS AS (CAST(si AS INT) / 2),
  cat VARCHAR(128) DEFAULT CURRENT_CATALOG,
  sch VARCHAR(128) DEFAULT CURRENT_SCHEMA,
  CHECK (si BETWEEN 0 AND 100),
  CONSTRAINT upper_vc CHECK (UPPER(vc) = vc OR vc IS NULL),
  CHECK (CHAR_LENGTH(c) > 0),
  CHECK (vc <> 'a\b' AND d < 1.5e10)
);
CREATE TABLE decimal_identity (id DECIMAL(10) GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE descending_identity (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH -1 INCREMENT BY -1), x INT);
CREATE TABLE unique_identity (id INT GENERATED BY DEFAULT AS IDENTITY UNIQUE, x INT);
CREATE TABLE no_rows (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
CREATE INDEX parent_name ON foo.parent (name DESC, id);
CREATE UNIQUE INDEX types_vc ON types (vc);
CREATE INDEX types_lv ON types (lv, vc);
CREATE INDEX types_c2 ON types (c2, c2_more);

