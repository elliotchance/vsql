#!/bin/sh

set -e

VSQL_FILE="$(mktemp).vsql" || exit 1
COPY_FILE="$(mktemp).vsql" || exit 1
SQL_FILE="$(mktemp).sql" || exit 1

$VSQL in $VSQL_FILE <<'SQL'
CREATE SCHEMA s;
CREATE SEQUENCE s.q START WITH 5;
SET SCHEMA 'S';
CREATE TABLE t (
    id INT PRIMARY KEY,
    x INT CHECK (t.x > 0),
    y INT CHECK (s.t.y > 0),
    g INT GENERATED ALWAYS AS (s.t.x + 1),
    label VARCHAR(20) DEFAULT 'S.T.X'
);
CREATE TABLE u (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    t_id INT,
    CONSTRAINT fk FOREIGN KEY (t_id) REFERENCES s.t (id)
);
INSERT INTO s.t (id, x, y) VALUES (1, 2, 3);
INSERT INTO s.u (t_id) VALUES (1);
SET SCHEMA 'PUBLIC';
SQL

check_no_schema() {
    if grep -E '"[Ss]"|CREATE SCHEMA|SET SCHEMA|[^'"'"']S\.T' $SQL_FILE; then
        echo "the schema is in the output of $1"
        exit 1
    fi
}

$VSQL out -no-schema $VSQL_FILE > $SQL_FILE
check_no_schema vsql
grep -F 'CREATE SEQUENCE "Q" START WITH 5' $SQL_FILE
grep -F 'CREATE TABLE "T" (' $SQL_FILE
grep -F 'GENERATED ALWAYS AS (T.X + 1)' $SQL_FILE
grep -F 'CHECK (T.Y > 0)' $SQL_FILE
grep -F 'INSERT INTO "T" (' $SQL_FILE
grep -F 'REFERENCES "T" ("ID")' $SQL_FILE
# A string isn't changed.
grep -F "DEFAULT 'S.T.X'" $SQL_FILE

# It can be loaded into any schema.
$VSQL in $COPY_FILE < $SQL_FILE
echo 'SELECT g FROM t; SELECT t_id FROM u;' | $VSQL in -verbose $COPY_FILE

for compat in sqlite3 mysql postgresql; do
    $VSQL out -no-schema -compat $compat $VSQL_FILE > $SQL_FILE
    check_no_schema $compat
    grep -F 'CREATE TABLE "t" (' $SQL_FILE
    grep -F 'REFERENCES "t" ("id")' $SQL_FILE
done
$VSQL out -no-schema -compat postgresql $VSQL_FILE | grep -F 'CREATE SEQUENCE "q"'

check_error() {
    if $VSQL out "$@" $VSQL_FILE > $SQL_FILE 2>&1; then
        echo "expected an error: $*"
        exit 1
    fi
    grep -F -- "$1" $SQL_FILE
}

check_error -no-schema -create-public-schema
check_error -no-schema -format csv -query 'SELECT * FROM s.t'
