grep -R 'CREATE SEQUENCE "PUBLIC"."SEQ1" START WITH 123 INCREMENT BY 5 MINVALUE 10;' $SQL_FILE
if grep -R "ALTER SEQUENCE" $SQL_FILE; then exit 1; fi

echo 'SELECT NEXT VALUE FOR seq1 FROM (VALUES 1) AS t;' | $VSQL in $VSQL_FILE
echo 'SELECT NEXT VALUE FOR seq1 FROM (VALUES 1) AS t;' | $VSQL in $VSQL_FILE

