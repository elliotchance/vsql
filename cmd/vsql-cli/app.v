fn register_app_command(mut cmd cli.Command) {
	mut app_cmd := cli.Command{
		name:          'app'
		description:   'Run a web server to browse the tables and their rows'
		usage:         '<file>'
		required_args: 1
		execute:       app_command
	}
	app_cmd.add_flag(cli.Flag{
		flag:        .string
		name:        'host'
		description: 'Address to listen on (default 127.0.0.1, use 0.0.0.0 or :: for every interface)'
	})
	app_cmd.add_flag(cli.Flag{
		flag:        .int
		name:        'port'
		abbrev:      'p'
		description: 'Port number (default 3211)'
	})
	cmd.add_command(app_cmd)
}

fn app_command(cmd cli.Command) ! {
	print_version()

	mut host := cmd.flags.get_string('host') or { '' }
	if host == '' {
		host = '127.0.0.1'
	}
	mut port := cmd.flags.get_int('port') or { 0 }
	if port == 0 {
		port = 3211
	}

	// Each request opens its own connection (so it sees the latest committed
	// data), they must share the same mutex like the server, see
	// ConnectionOptions.
	mut options := vsql.default_connection_options()
	options.mutex = sync.new_rwmutex()

	mut family := net.AddrFamily.ip
	mut address := '${host}:${port}'
	if host.contains(':') {
		family = .ip6
		address = '[${host}]:${port}'
	}
	mut listener := net.listen_tcp(family, address) or {
		return error('cannot listen on ${address}: ${err}')
	}
	println('ready on http://${listener.addr()!}')

	create_tabs(cmd.args[0], options)!

	app := &App{
		db_file: cmd.args[0]
		options: options
	}
	for {
		mut conn := listener.accept() or { continue }
		spawn app.handle(mut conn)
	}
}

struct App {
	db_file string
	options vsql.ConnectionOptions
mut:
	// results is the last result of each tab (by id), so it's shown again
	// without running the tab when switching back to it. They are not kept
	// when the app is restarted.
	results shared map[int]TabResult
}

struct TabResult {
	// status is the number of rows (or the message of a statement) and the
	// time, shown next to the Run button.
	status string
	// output is the HTML of the rows or error.
	output string
	// error is from a change to a row (see app_edit.v), which is shown above
	// the output. It's not kept.
	error string
}

// create_tabs creates VSQL_APP.TABS, which has the title and SQL of each tab in the
// editor (and which tab is active) so they are restored the next time the file
// is opened. It starts empty, the home tab isn't a row.
fn create_tabs(db_file string, options vsql.ConnectionOptions) ! {
	mut conn := vsql.open_database(db_file, options)!
	defer {
		conn.close()
	}

	mut catalog := conn.catalog()
	if !catalog.schemas()!.any(it.name == 'VSQL_APP') {
		conn.query('CREATE SCHEMA vsql_app')!
	}
	mut tables := conn.query("SELECT COUNT(*) AS c FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'VSQL_APP' AND TABLE_NAME = 'TABS'")!
	for row in tables {
		if row.get_int('C')! > 0 {
			return
		}
	}

	conn.query('CREATE TABLE vsql_app.tabs (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(50) NOT NULL, query_text VARCHAR(1000000) NOT NULL, active BOOLEAN NOT NULL)')!
}

// home_tab is the first tab, which can't be closed. It lists the tables and is
// shown when no tab is active. The ids in VSQL_APP.TABS start at 1.
const home_tab = Tab{
	id: 0
}

struct Tab {
	id         int
	title      string
	query_text string
	active     bool
}

fn tabs(mut conn vsql.Connection) ![]Tab {
	mut tabs := []Tab{}
	for row in conn.query('SELECT id, title, query_text, active FROM vsql_app.tabs ORDER BY id')! {
		tabs << Tab{row.get_int('ID')!, row.get_string('TITLE')!, row.get_string('QUERY_TEXT')!, row.get_bool('ACTIVE')! == .is_true}
	}

	return tabs
}

// add_tab adds a tab after the others, makes it active and returns its id.
fn add_tab(mut conn vsql.Connection, query_text string) !int {
	mut stmt := conn.prepare('INSERT INTO vsql_app.tabs (title, query_text, active) VALUES (:title, :query_text, FALSE)')!
	stmt.query({
		'title':      vsql.new_varchar_value(tab_title(query_text))
		'query_text': vsql.new_varchar_value(query_text)
	})!
	mut id := 0
	for row in conn.query('SELECT MAX(id) AS id FROM vsql_app.tabs')! {
		id = row.get_int('ID')!
	}
	activate_tab(mut conn, id)!

	return id
}

// activate_tab makes a tab active, or the home tab if id is 0.
fn activate_tab(mut conn vsql.Connection, id int) ! {
	conn.query('UPDATE vsql_app.tabs SET active = FALSE WHERE active')!
	if id == home_tab.id {
		return
	}
	mut stmt := conn.prepare('UPDATE vsql_app.tabs SET active = TRUE WHERE id = :id')!
	stmt.query({
		'id': vsql.new_integer_value(id)
	})!
}

// title_tab sets the title of a tab when it's run.
fn title_tab(mut conn vsql.Connection, id int, query_text string) ! {
	mut stmt := conn.prepare('UPDATE vsql_app.tabs SET title = :title WHERE id = :id')!
	stmt.query({
		'title': vsql.new_varchar_value(tab_title(query_text))
		'id':    vsql.new_integer_value(id)
	})!
}

fn save_tab(mut conn vsql.Connection, id int, query_text string) ! {
	mut stmt := conn.prepare('UPDATE vsql_app.tabs SET query_text = :query_text WHERE id = :id')!
	stmt.query({
		'query_text': vsql.new_varchar_value(query_text)
		'id':         vsql.new_integer_value(id)
	})!
}

// handle answers a single HTTP request and closes the connection. A GET shows
// the active tab. The tabs and editor are one form that POSTs with the
// current tab, so the SQL in the editor is always saved before running it, or
// switching, adding or closing a tab.
fn (app &App) handle(mut conn net.TcpConn) {
	defer {
		conn.close() or {}
	}
	conn.set_read_timeout(10 * time.second)
	mut reader := io.new_buffered_reader(reader: conn)
	defer {
		reader.free()
	}

	// For example: "GET / HTTP/1.1"
	parts := (reader.read_line() or { return }).split(' ')
	if parts.len != 3 {
		write_response(mut conn, '400 Bad Request', 'text/plain', 'bad request')
		return
	}
	method, url := parts[0], parts[1]
	if method !in ['GET', 'POST'] || url.all_before('?') != '/' {
		write_response(mut conn, '404 Not Found', 'text/plain', 'not found')
		return
	}

	mut content_length := 0
	for {
		line := reader.read_line() or { return }
		if line == '' {
			break
		}
		if line.to_lower().starts_with('content-length:') {
			content_length = line.all_after(':').trim_space().int()
		}
	}

	mut body := []u8{len: content_length}
	mut n := 0
	for n < content_length {
		n += reader.read(mut body[n..]) or { return }
	}

	form := urllib.parse_query(body.bytestr()) or { urllib.new_values() }
	response := app.respond(method == 'POST', form) or {
		write_response(mut conn, '500 Internal Server Error', 'text/plain', err.msg())
		return
	}
	if response.starts_with('/') {
		conn.write_string('HTTP/1.0 303 See Other\r\nLocation: ${response}\r\nContent-Length: 0\r\nConnection: close\r\n\r\n') or {}
	} else {
		write_response(mut conn, '200 OK', 'text/html; charset=utf-8', response)
	}
}

fn write_response(mut conn net.TcpConn, status string, content_type string, body string) {
	conn.write_string('HTTP/1.0 ${status}\r\nContent-Type: ${content_type}\r\nContent-Length: ${body.len}\r\nConnection: close\r\n\r\n${body}') or {}
}

// respond returns the page, or the URL (starting with /) to redirect to.
fn (app &App) respond(is_post bool, form urllib.Values) !string {
	mut conn := vsql.open_database(app.db_file, app.options)!
	defer {
		conn.close()
	}

	all_tabs := tabs(mut conn)!

	// Showing a tab doesn't run it (that's only done with Run), it shows the
	// last result.
	if !is_post {
		tab := all_tabs.filter(it.active)[0] or { home_tab }
		if tab.id == home_tab.id {
			return app.home_page(mut conn, all_tabs)
		}
		result := rlock app.results {
			app.results[tab.id] or { TabResult{} }
		}
		return app.page(all_tabs, tab, result, '')
	}

	// Query (on the home tab) opens a new tab that runs SELECT * on a table.
	if table := form.get('query') {
		query_text := 'SELECT * FROM ${table}'
		id := add_tab(mut conn, query_text)!
		result := run_query(mut conn, query_text)!
		lock app.results {
			app.results[id] = result
		}
		return '/'
	}

	tab_id := (form.get('tab') or { '' }).int()
	tab := all_tabs.filter(it.id == tab_id)[0] or { home_tab }

	// The home tab has no SQL to save or run.
	query_text := form.get('sql') or { tab.query_text }
	if tab.id != home_tab.id {
		save_tab(mut conn, tab.id, query_text)!
	}

	if other_tab := form.get('goto') {
		activate_tab(mut conn, other_tab.int())!
		return '/'
	}
	if _ := form.get('new') {
		add_tab(mut conn, show_tables_sql)!
		return '/'
	}
	if close := form.get('close') {
		mut stmt := conn.prepare('DELETE FROM vsql_app.tabs WHERE id = :id')!
		stmt.query({
			'id': vsql.new_integer_value(close.int())
		})!
		lock app.results {
			app.results.delete(close.int())
		}

		// Closing the active tab activates the first tab, or the home tab if
		// it was the last one.
		if close.int() == tab.id {
			activate_tab(mut conn, (tabs(mut conn)![0] or { home_tab }).id)!
		}
		return '/'
	}
	if tab.id == home_tab.id {
		return '/'
	}

	// A change to a row of an editable result (see app_edit.v). An update or
	// delete is shown to be confirmed before it's run, an insert is run
	// straight away. If it fails, the values entered to insert are kept.
	if kind := form.get('change') {
		last := rlock app.results {
			app.results[tab.id] or { TabResult{} }
		}
		table := find_edit_table(mut conn, form.get('schema') or { '' }, form.get('table') or {
			''
		})!
		change_sql := build_change(table, form) or {
			return app.page(all_tabs, tab, TabResult{
				...last
				error: err.msg()
			}, '')
		}
		if kind != 'insert' {
			return app.page(all_tabs, tab, last, change_sql)
		}
		app.apply_change(mut conn, tab.id, change_sql, query_text) or {
			return app.page(all_tabs, tab, TabResult{
				...last
				output: keep_insert_values(last.output, form)
				error:  err.msg()
			}, '')
		}
		return '/'
	}
	if change_sql := form.get('confirm') {
		app.apply_change(mut conn, tab.id, change_sql, query_text) or {
			last := rlock app.results {
				app.results[tab.id] or { TabResult{} }
			}
			return app.page(all_tabs, tab, TabResult{
				...last
				error: err.msg()
			}, '')
		}
		return '/'
	}

	result := run_query(mut conn, query_text)!
	lock app.results {
		app.results[tab.id] = result
	}
	title_tab(mut conn, tab.id, query_text)!
	activate_tab(mut conn, tab.id)!
	return app.page(tabs(mut conn)!, Tab{tab.id, tab_title(query_text), query_text, true},
		result, '')
}

// apply_change runs a change to a row (see run_change), then the SQL of the tab
// again to show it.
fn (app &App) apply_change(mut conn vsql.Connection, tab_id int, change_sql string, query_text string) ! {
	msg := run_change(mut conn, change_sql)!
	result := run_query(mut conn, query_text)!
	lock app.results {
		app.results[tab_id] = TabResult{
			...result
			status: '${msg}, ${result.status}'
		}
	}
}

// run_query runs every statement and returns the result of the last one.
fn run_query(mut conn vsql.Connection, query_text string) !TabResult {
	mut status := ''
	mut output := strings.new_builder(4096)
	// Every statement is run, the result of the last one is shown. The time
	// is for all of the statements, like the CLI.
	start := time.ticks()
	mut result := vsql.Result{}
	mut failed := false
	for stmt in vsql.split_statements(query_text) {
		result = conn.query(stmt) or {
			output.write_string('<p class="error">${html_escape(err.msg())}</p>')
			failed = true
			break
		}
	}
	elapsed := time.ticks() - start
	if failed {
		status = 'Error (${elapsed} ms)'
	} else if result.msg != '' {
		status = '${result.msg} (${elapsed} ms)'
	} else if result.columns.len > 0 {
		// The rows of SELECT * FROM a table can be changed (see app_edit.v
		// and app.js). A row can only be updated or deleted if the table has a
		// PRIMARY KEY.
		edit := editable_table(mut conn, query_text, result)
		mut has_key := false
		if table := edit {
			has_key = table.primary_key.len > 0
			output.write_string('<table class="editable" data-schema="${html_escape(table.schema)}" data-table="${html_escape(table.name)}"><thead><tr><th></th>')
		} else {
			output.write_string('<table><thead><tr>')
		}
		for column in result.columns {
			output.write_string('<th>${html_escape(column.name.sub_entity_name)}<span class="type">${html_escape(column.typ.str())}</span></th>')
		}
		output.write_string('</tr></thead><tbody>')
		mut count := 0
		for row in result {
			if table := edit {
				if has_key {
					output.write_string('<tr data-key="${html_escape(row_key(table, row)!)}"><td class="row-actions"><button type="button" class="delete" title="Delete">&times;</button></td>')
				} else {
					output.write_string('<tr><td class="row-actions"></td>')
				}
			} else {
				output.write_string('<tr>')
			}
			for i, column in result.columns {
				value := row.get_column(column)!
				mut attrs := if value.is_null { ' class="null"' } else { '' }
				if table := edit {
					if has_key && !table.columns[i].generated {
						attrs += ' data-column="${html_escape(column.name.sub_entity_name)}" title="Double-click to edit"'
						if column.typ.typ == .is_boolean {
							attrs += ' data-boolean'
						}
					}
				}
				output.write_string('<td${attrs}>${html_escape(value.str())}</td>')
			}
			output.write_string('</tr>')
			count++
		}
		output.write_string('</tbody>')
		if table := edit {
			output.write_string('<tfoot><tr class="insert"><td class="row-actions"><button type="button" class="add" title="Add">+</button></td>')
			for column in table.columns {
				if column.generated {
					output.write_string('<td class="null">generated</td>')
				} else if column.typ.typ == .is_boolean {
					output.write_string('<td><select data-column="${html_escape(column.name)}"><option value="">DEFAULT</option><option>UNKNOWN</option><option>TRUE</option><option>FALSE</option></select></td>')
				} else {
					output.write_string('<td><input data-column="${html_escape(column.name)}" placeholder="DEFAULT" spellcheck="false"></td>')
				}
			}
			output.write_string('</tr></tfoot>')
		}
		output.write_string('</table>')
		status = '${count} ${vsql.pluralize(count, 'row')} (${elapsed} ms)'
	}

	return TabResult{
		status: status
		output: output.str()
	}
}

// page renders the tabs, the SQL editor for tab and its last result. If
// change_sql isn't empty, it's shown to be confirmed before it's run.
fn (app &App) page(all_tabs []Tab, tab Tab, result TabResult, change_sql string) !string {
	mut sb := strings.new_builder(4096)
	write_tabs(mut sb, all_tabs, tab)

	status := result.status
	output := if result.output == '' && result.status == '' {
		'<p class="empty">Run to see the result.</p>'
	} else {
		result.output
	}

	// The editor is a transparent textarea over a highlighted copy of its text
	// (see app.js).
	sb.write_string('<div class="editor"><pre aria-hidden="true"></pre>')
	autofocus := if change_sql == '' { ' autofocus' } else { '' }
	sb.write_string('<textarea name="sql" rows="6" spellcheck="false"${autofocus} placeholder="SELECT * FROM ...">${html_escape(tab.query_text)}</textarea></div>')
	sb.write_string('<div class="actions"><span class="status">${html_escape(status)}</span>')
	sb.write_string('<button type="submit" class="run" title="Run (Ctrl+Enter)">Run <span class="shortcut">&#8963;&#8629;</span></button></div></form>')
	if change_sql != '' {
		// It's a popup (see app.js), a DELETE is run with a red button.
		run_class := if change_sql.starts_with('DELETE ') { ' class="delete"' } else { '' }
		sb.write_string('<dialog class="confirm"><form method="post" action="/"><input type="hidden" name="tab" value="${tab.id}">')
		sb.write_string('<input type="hidden" name="confirm" value="${html_escape(change_sql)}"><pre class="sql">${html_escape(change_sql)}</pre>')
		sb.write_string('<button type="submit"${run_class} autofocus>Run</button><a href="/" class="cancel">Cancel</a></form></dialog>')
	}
	if result.error != '' {
		sb.write_string('<p class="error">${html_escape(result.error)}</p>')
	}
	sb.write_string(output)
	// The script is after the result, so it can find the editable table.
	reserved_words := vsql.reserved_words().map('"${it}"').join(',')
	sb.write_string('<script>const reservedWords = new Set([${reserved_words}]);${app_js.to_string()}</script>')

	sb.write_string('</main></body></html>')
	return sb.str()
}

// home_page renders the tabs and the tables, each with a button to query it in a new tab.
fn (app &App) home_page(mut conn vsql.Connection, all_tabs []Tab) !string {
	mut sb := strings.new_builder(4096)
	write_tabs(mut sb, all_tabs, home_tab)

	// The tables are under their schema (a schema without tables isn't
	// shown), both sorted by name.
	mut catalog := conn.catalog()
	mut schemas := map[string][]vsql.Identifier{}
	for schema in catalog.schemas()! {
		for table in catalog.schema_tables(schema.name)! {
			// The catalog is the file, so it's left out.
			schemas[schema.name] << vsql.Identifier{
				...table.name
				catalog_name: ''
			}
		}
	}
	mut schema_names := schemas.keys()
	schema_names.sort()

	if schema_names.len == 0 {
		sb.write_string('<p class="empty">There are no tables.</p>')
	}
	for schema_name in schema_names {
		mut tables := schemas[schema_name].clone()
		tables.sort(a.entity_name < b.entity_name)
		sb.write_string('<details class="schema" open><summary>${html_escape(schema_name)} <span class="count">${tables.len} ${vsql.pluralize(tables.len, 'table')}</span></summary><table class="tables"><tbody>')
		for table in tables {
			sb.write_string('<tr><td>${html_escape(table.entity_name)}</td><td><button type="submit" name="query" value="${html_escape(table.str())}">Query</button></td></tr>')
		}
		sb.write_string('</tbody></table></details>')
	}

	sb.write_string('</form></main></body></html>')
	return sb.str()
}

// write_tabs starts the page and its form, with the tabs (tab is the active
// one). The form must be closed by the caller.
fn write_tabs(mut sb strings.Builder, all_tabs []Tab, tab Tab) {
	sb.write_string('<!doctype html><html><head><meta charset="utf-8">')
	sb.write_string('<meta name="viewport" content="width=device-width, initial-scale=1">')
	sb.write_string('<title>vsql</title><style>${app_css}</style></head><body><main>')

	sb.write_string('<form method="post" action="/"><input type="hidden" name="tab" value="${tab.id}"><div class="tabs">')
	home_active := if tab.id == home_tab.id { ' active' } else { '' }
	sb.write_string('<span class="tab home${home_active}"><button type="submit" name="goto" value="${home_tab.id}" title="Home">${home_icon}</button></span>')
	for t in all_tabs {
		active := if t.id == tab.id { ' active' } else { '' }
		sb.write_string('<span class="tab${active}"><button type="submit" name="goto" value="${t.id}">${html_escape(t.title)}</button>')
		sb.write_string('<button type="submit" name="close" value="${t.id}" class="close" title="Close">&times;</button></span>')
	}
	sb.write_string('<button type="submit" name="new" value="1" class="new" title="New tab">+</button>')
	// A local build has no version.
	version := vsql_version() or { 'v0.0.0' }
	sb.write_string('<span class="version">vsql ${html_escape(version)}</span></div>')
}

const home_icon = '<svg width="16" height="16" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true"><path d="M8 1.5 1 7.5h2V14h4v-4h2v4h4V7.5h2z"/></svg>'

