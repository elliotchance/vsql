#!/usr/bin/env bash

# all-examples.sh writes examples/all/main.v, which runs every example in
# examples/ from one program, so that "make examples-test" builds vsql once for
# all of them, rather than once for each example (about a minute each, with
# -prod).
#
# Each example has a main() and an example() (see examples/simple.v). They're
# renamed after the example (such as main_simple() and example_simple()), and
# the main() of the whole file calls each main_...() in turn. The imports are put
# once at the top. The examples must not have the same names as each other at
# the top level, other than main() and example().
#
# Each example runs in its own folder (examples/all/NAME/), since they use the
# same file names (such as test.vsql), and on Windows an example can't remove
# the file while an example before it still has it open.
#
# examples/all/main.v is only replaced when it's different, so that make doesn't
# build it again.

set -euo pipefail

out=examples/all/main.v
mkdir -p examples/all

tmp="$(mktemp)"
{
  echo "// Generated by scripts/all-examples.sh from examples/*.v. Don't edit it,"
  echo "// it's made again by \"make examples-test\"."
  { echo 'import os'; grep -h '^import ' examples/*.v; } | sort -u
  for file in examples/*.v; do
    name="$(basename "$file" .v | tr - _)"
    echo
    echo "// $file"
    echo
    perl -ne "next if /^import /; s/^fn main\(\)/fn main_$name()/; s/\bexample\(\)/example_$name()/g; print" "$file"
  done
  echo
  echo "fn main() {"
  echo "	dir := os.getwd()"
  for file in examples/*.v; do
    name="$(basename "$file" .v | tr - _)"
    echo "	println('$file')"
    echo "	os.mkdir_all('examples/all/$name') or { panic(err) }"
    echo "	os.chdir('examples/all/$name') or { panic(err) }"
    echo "	main_$name()"
    echo "	os.chdir(dir) or { panic(err) }"
  done
  echo "}"
} > "$tmp"

if cmp -s "$tmp" "$out"; then
  rm "$tmp"
else
  mv "$tmp" "$out"
fi
