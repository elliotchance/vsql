#!/usr/bin/env bash

# all-tests.sh writes vsql/all_test.v, which has all of the V tests in vsql/
# (vsql/*_test.v: the SQL, unit and B-tree tests) in one file. Each test file is
# built on its own with all of vsql, which takes up to a few minutes when it's
# optimized, so "make test" builds this one instead (see all-test in the Makefile).
#
# The files are put one after the other, without their module and import lines,
# which are put once at the top. Each file's testsuite_begin and testsuite_end
# are renamed (such as testsuite_begin_sql_test), and they're called from the
# testsuite_begin and testsuite_end of the whole file, so that a test can still
# run itself in another process (such as the SQL tests do for each CPU). The
# test files must not have the same names as each other at the top level.
#
# vsql/all_test.v is only replaced when it's different, so that make doesn't
# build it again.

set -euo pipefail

out=vsql/all_test.v
files=()
for file in vsql/*_test.v; do
  if [ "$file" != "$out" ]; then
    files+=("$file")
  fi
done

tmp="$(mktemp)"
{
  echo "// Generated by scripts/all-tests.sh from vsql/*_test.v. Don't edit it, it's"
  echo "// made again by \"make all-test\"."
  echo "module vsql"
  echo
  grep -h '^import ' "${files[@]}" | sort -u
  for file in "${files[@]}"; do
    name="$(basename "$file" .v)"
    echo
    echo "// $file"
    echo
    sed -E -e '/^module /d' -e '/^import /d' \
      -e "s/^fn testsuite_(begin|end)\(\)/fn testsuite_\1_$name()/" "$file"
  done
  for hook in begin end; do
    calls="$(grep -l "^fn testsuite_$hook()" "${files[@]}" || true)"
    if [ -n "$calls" ]; then
      echo
      echo "fn testsuite_$hook() {"
      for file in $calls; do
        echo "	testsuite_${hook}_$(basename "$file" .v)()"
      done
      echo "}"
    fi
  done
} > "$tmp"

if cmp -s "$tmp" "$out"; then
  rm "$tmp"
else
  mv "$tmp" "$out"
fi
