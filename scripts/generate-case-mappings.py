#!/usr/bin/env python3
"""generate-case-mappings.py prints vsql/case_mappings.v.

  scripts/generate-case-mappings.py > vsql/case_mappings.v

The full (one-to-many) Unicode case mappings come from the Unicode version of
this Python. Only the characters that <fold> is defined to replace are included,
by their General Category, so a letter-like symbol such as a circled letter
isn't changed. A mapping that depends on the surrounding characters is not used.
"""

import sys
import unicodedata


def mappings(categories, fold):
    for code_point in range(sys.maxunicode + 1):
        c = chr(code_point)
        if unicodedata.category(c) in categories and fold(c) != c:
            yield code_point, [ord(x) for x in fold(c)]


def print_table(name, categories, fold):
    print(f"const {name} = [")
    for code_point, to in mappings(categories, fold):
        to += [0] * (3 - len(to))
        args = ", ".join(f"{x:#x}" for x in [code_point] + to)
        print(f"\tCaseMapping{{{args}}},")
    print("]")


print(f"""// This file is generated by scripts/generate-case-mappings.py from Unicode
// {unicodedata.unidata_version}. Do not edit it by hand.

module vsql

// upper_case_mappings has the lower case (Ll) and title case (Lt) characters that
// have a corresponding upper case character or characters, ordered by from.
//
// ISO/IEC 9075-2:2016(E), 6.32, <string value function>, General Rules, 7.d.i""")
print_table("upper_case_mappings", ["Ll", "Lt"], str.upper)
print("""
// lower_case_mappings has the upper case (Lu) and title case (Lt) characters that
// have a corresponding lower case character or characters, ordered by from.
//
// ISO/IEC 9075-2:2016(E), 6.32, <string value function>, General Rules, 7.d.ii""")
print_table("lower_case_mappings", ["Lu", "Lt"], str.lower)
