#!/usr/bin/env python3
"""generate-unicode-tables.py writes the data behind normalize_nfc (in
vsql/unicode_normalization.v) to stdout from Python's unicodedata. To move to a
newer version of Unicode:

  scripts/generate-unicode-tables.py > vsql/unicode_tables.v
  v fmt -w vsql/unicode_tables.v
"""

import unicodedata


def table(name, comment, entries):
    lines = ['// ' + line for line in comment]
    values = [f'u64({entries[0]:#x})'] + [f'{entry:#x}' for entry in entries[1:]]
    lines.append(f'const {name} = [' + ', '.join(values) + ']')
    return '\n'.join(lines)


classes = []
decompositions = []
compositions = []
for code_point in range(0x110000):
    char = chr(code_point)
    if unicodedata.combining(char):
        classes.append(code_point << 8 | unicodedata.combining(char))

    # A tag (such as "<compat>") makes it a compatibility mapping, not canonical.
    mapping = unicodedata.decomposition(char).split()
    if not mapping or mapping[0].startswith('<'):
        continue

    first = int(mapping[0], 16)
    second = int(mapping[1], 16) if len(mapping) > 1 else 0
    decompositions.append(code_point << 42 | first << 21 | second)

    # Anything that's excluded from composition doesn't survive NFC.
    if second and unicodedata.normalize('NFC', char) == char:
        compositions.append(first << 42 | second << 21 | code_point)

print('module vsql\n')
print(f'// Generated by scripts/generate-unicode-tables.py from Unicode '
      f'{unicodedata.unidata_version}.\n')
print(table('unicode_combining_classes', [
    'unicode_combining_classes has every code point with a non-zero canonical',
    'combining class, sorted as: code point << 8 | class',
], classes))
print()
print(table('unicode_decompositions', [
    'unicode_decompositions has every canonical mapping, sorted as:',
    'code point << 42 | first << 21 | second (zero for a single code point)',
], decompositions))
print()
print(table('unicode_compositions', [
    'unicode_compositions has every pair that composes, sorted as:',
    'first << 42 | second << 21 | composite',
], sorted(compositions)))
