-- # Whether a sequence has returned a value yet is stored, so it's the same for
-- # another connection.
/* connection 1 */
CREATE SEQUENCE seq1 START WITH 10;
CREATE SEQUENCE seq2 START WITH 10;
SELECT NEXT VALUE FOR seq2 FROM (VALUES 1) AS t;
/* connection 2 */
ALTER SEQUENCE seq1 INCREMENT BY 3;
ALTER SEQUENCE seq2 INCREMENT BY 3;
SELECT NEXT VALUE FOR seq1 FROM (VALUES 1) AS t;
SELECT NEXT VALUE FOR seq2 FROM (VALUES 1) AS t;
