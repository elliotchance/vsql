-- # Every <datetime value function> in a statement has the same time, the
-- # statement timestamp, which is read once for each statement. "clock tick" is
-- # a second later each time the clock is read.
/* clock tick */
VALUES ROW(CURRENT_DATE, CURRENT_TIME, LOCALTIME(6), CURRENT_TIMESTAMP(6), LOCALTIMESTAMP(0));
VALUES CURRENT_TIME;
VALUES ROW(CURRENT_TIME = CURRENT_TIME, CURRENT_TIMESTAMP = CURRENT_TIMESTAMP, LOCALTIME(6) = CAST(LOCALTIMESTAMP AS TIME(6)));
