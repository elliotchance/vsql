-- # The PRIMARY KEY comes first, then the check constraints (including NOT
-- # NULL) with the same names as in CHECK_CONSTRAINTS. They're never deferrable.
CREATE TABLE t (a INT CHECK (a > 0) NOT NULL, b INT, PRIMARY KEY (b), CHECK (b <> a));
SELECT * FROM information_schema.table_constraints;
-- msg: CREATE TABLE 1
-- CONSTRAINT_CATALOG: :memory: CONSTRAINT_SCHEMA: PUBLIC CONSTRAINT_NAME: T_PRIMARY_KEY TABLE_CATALOG: :memory: TABLE_SCHEMA: PUBLIC TABLE_NAME: T CONSTRAINT_TYPE: PRIMARY KEY IS_DEFERRABLE: NO INITIALLY_DEFERRED: NO ENFORCED: YES
-- CONSTRAINT_CATALOG: :memory: CONSTRAINT_SCHEMA: PUBLIC CONSTRAINT_NAME: T_NOT_NULL_1 TABLE_CATALOG: :memory: TABLE_SCHEMA: PUBLIC TABLE_NAME: T CONSTRAINT_TYPE: CHECK IS_DEFERRABLE: NO INITIALLY_DEFERRED: NO ENFORCED: YES
