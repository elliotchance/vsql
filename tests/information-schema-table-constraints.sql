-- # Tables are ordered by schema and name, and a table without constraints
-- # doesn't have any rows.
CREATE SCHEMA s;
CREATE TABLE s.a ("my col" INT PRIMARY KEY);
CREATE TABLE "Mixed" (x INT CHECK (x > 0));
CREATE TABLE z (x INT);
SELECT constraint_schema, constraint_name, table_schema, table_name, constraint_type FROM information_schema.table_constraints;
-- msg: CREATE SCHEMA 1
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
-- CONSTRAINT_SCHEMA: PUBLIC CONSTRAINT_NAME: Mixed_CHECK_1 TABLE_SCHEMA: PUBLIC TABLE_NAME: Mixed CONSTRAINT_TYPE: CHECK
-- CONSTRAINT_SCHEMA: S CONSTRAINT_NAME: A_PRIMARY_KEY TABLE_SCHEMA: S TABLE_NAME: A CONSTRAINT_TYPE: PRIMARY KEY
-- CONSTRAINT_SCHEMA: S CONSTRAINT_NAME: A_NOT_NULL_1 TABLE_SCHEMA: S TABLE_NAME: A CONSTRAINT_TYPE: CHECK

-- # Every check constraint is in CHECK_CONSTRAINTS, but a PRIMARY KEY isn't.
CREATE TABLE t (a INT PRIMARY KEY, b INT NOT NULL, CHECK (b > a));
SELECT tc.constraint_name, cc.check_clause FROM information_schema.table_constraints AS tc LEFT JOIN information_schema.check_constraints AS cc ON cc.constraint_name = tc.constraint_name;
-- msg: CREATE TABLE 1
-- CONSTRAINT_NAME: T_PRIMARY_KEY CHECK_CLAUSE: NULL
-- CONSTRAINT_NAME: T_NOT_NULL_1 CHECK_CLAUSE: A IS NOT NULL
-- CONSTRAINT_NAME: T_NOT_NULL_2 CHECK_CLAUSE: B IS NOT NULL
-- CONSTRAINT_NAME: T_CHECK_1 CHECK_CLAUSE: B > A

-- # The constraints are read back from the file the same.
/* connection 1 */
CREATE TABLE t (a INT PRIMARY KEY);
/* connection 2 */
SELECT constraint_catalog, constraint_name, table_catalog, constraint_type FROM information_schema.table_constraints;
-- 1: msg: CREATE TABLE 1
-- 2: CONSTRAINT_CATALOG: test CONSTRAINT_NAME: T_PRIMARY_KEY TABLE_CATALOG: test CONSTRAINT_TYPE: PRIMARY KEY
-- 2: CONSTRAINT_CATALOG: test CONSTRAINT_NAME: T_NOT_NULL_1 TABLE_CATALOG: test CONSTRAINT_TYPE: CHECK

-- # A constraint is removed with its table.
CREATE TABLE t (a INT PRIMARY KEY);
DROP TABLE t;
SELECT * FROM information_schema.table_constraints;
-- msg: CREATE TABLE 1
-- msg: DROP TABLE 1

-- # Each UNIQUE comes after the PRIMARY KEY, numbered in the order they're
-- # defined, on a column or the table.
CREATE TABLE t (a INT UNIQUE, b INT CHECK (b > 0), PRIMARY KEY (b), UNIQUE (a, b), c INT UNIQUE);
SELECT constraint_name, constraint_type FROM information_schema.table_constraints;
-- msg: CREATE TABLE 1
-- CONSTRAINT_NAME: T_PRIMARY_KEY CONSTRAINT_TYPE: PRIMARY KEY
-- CONSTRAINT_NAME: T_UNIQUE_1 CONSTRAINT_TYPE: UNIQUE
-- CONSTRAINT_NAME: T_UNIQUE_2 CONSTRAINT_TYPE: UNIQUE
-- CONSTRAINT_NAME: T_UNIQUE_3 CONSTRAINT_TYPE: UNIQUE
-- CONSTRAINT_NAME: T_NOT_NULL_2 CONSTRAINT_TYPE: CHECK
-- CONSTRAINT_NAME: T_CHECK_1 CONSTRAINT_TYPE: CHECK

-- # Each FOREIGN KEY comes after the UNIQUE constraints, numbered in the order
-- # they're defined, on a column or the table.
CREATE TABLE t (a INT PRIMARY KEY REFERENCES t, b INT UNIQUE, FOREIGN KEY (b) REFERENCES t (b));
SELECT constraint_name, constraint_type FROM information_schema.table_constraints;
-- msg: CREATE TABLE 1
-- CONSTRAINT_NAME: T_PRIMARY_KEY CONSTRAINT_TYPE: PRIMARY KEY
-- CONSTRAINT_NAME: T_UNIQUE_1 CONSTRAINT_TYPE: UNIQUE
-- CONSTRAINT_NAME: T_FOREIGN_KEY_1 CONSTRAINT_TYPE: FOREIGN KEY
-- CONSTRAINT_NAME: T_FOREIGN_KEY_2 CONSTRAINT_TYPE: FOREIGN KEY
-- CONSTRAINT_NAME: T_NOT_NULL_1 CONSTRAINT_TYPE: CHECK
