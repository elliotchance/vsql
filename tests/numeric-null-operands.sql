-- # Arithmetic and every numeric function return NULL when an operand is NULL.

VALUES ROW(1 + CAST(NULL AS INTEGER), CAST(NULL AS DOUBLE PRECISION) * 2.5e0, -CAST(NULL AS INTEGER));
-- COL1: NULL COL2: NULL COL3: NULL

VALUES ROW(CHAR_LENGTH(CAST(NULL AS VARCHAR(10))), OCTET_LENGTH(CAST(NULL AS VARCHAR(10))), POSITION(CAST(NULL AS VARCHAR(10)) IN 'abc'), POSITION('a' IN CAST(NULL AS VARCHAR(10))));
-- COL1: NULL COL2: NULL COL3: NULL COL4: NULL

VALUES ROW(ABS(CAST(NULL AS INTEGER)), ABS(CAST(NULL AS DOUBLE PRECISION)));
-- COL1: NULL COL2: NULL

VALUES ROW(MOD(CAST(NULL AS INTEGER), 3), MOD(3, CAST(NULL AS INTEGER)));
-- COL1: NULL COL2: NULL

VALUES ROW(SIN(CAST(NULL AS DOUBLE PRECISION)), COS(CAST(NULL AS DOUBLE PRECISION)), TAN(CAST(NULL AS DOUBLE PRECISION)), ASIN(CAST(NULL AS DOUBLE PRECISION)), ACOS(CAST(NULL AS DOUBLE PRECISION)), ATAN(CAST(NULL AS DOUBLE PRECISION)), SINH(CAST(NULL AS DOUBLE PRECISION)), COSH(CAST(NULL AS DOUBLE PRECISION)), TANH(CAST(NULL AS DOUBLE PRECISION)));
-- COL1: NULL COL2: NULL COL3: NULL COL4: NULL COL5: NULL COL6: NULL COL7: NULL COL8: NULL COL9: NULL

VALUES LOG10(CAST(NULL AS DOUBLE PRECISION));
-- COL1: NULL

VALUES ROW(LN(CAST(NULL AS DOUBLE PRECISION)), EXP(CAST(NULL AS DOUBLE PRECISION)));
-- COL1: NULL COL2: NULL

VALUES ROW(POWER(CAST(NULL AS DOUBLE PRECISION), 2.0e0), POWER(2.0e0, CAST(NULL AS DOUBLE PRECISION)), SQRT(CAST(NULL AS DOUBLE PRECISION)));
-- COL1: NULL COL2: NULL COL3: NULL

VALUES ROW(FLOOR(CAST(NULL AS DOUBLE PRECISION)), FLOOR(CAST(NULL AS NUMERIC(5, 2))), CEIL(CAST(NULL AS DOUBLE PRECISION)), CEILING(CAST(NULL AS NUMERIC(5, 2))));
-- COL1: NULL COL2: NULL COL3: NULL COL4: NULL

-- # A <numeric primary> must be numeric.
VALUES 'a' + 1;
-- error 42883: operator does not exist: CHARACTER + SMALLINT

VALUES 1 * TRUE;
-- error 42883: operator does not exist: SMALLINT * BOOLEAN

-- # "--" always starts a comment, so "3 --1" is 3.
VALUES 3 --1
;
-- COL1: 3

VALUES 3 - -1;
-- COL1: 4
