-- # A constraint has the schema of its table, even when it references a table
-- # in another schema. A CHECK that doesn't use any columns isn't in the view,
-- # and a table without constraints doesn't have any rows.
CREATE SCHEMA s;
CREATE TABLE s.p ("my id" INT PRIMARY KEY);
CREATE TABLE c (r INT REFERENCES s.p, CHECK (1 = 1), CHECK (c.r <> 0));
CREATE TABLE z (x INT);
SELECT table_schema, table_name, column_name, constraint_schema, constraint_name FROM information_schema.constraint_column_usage;
-- msg: CREATE SCHEMA 1
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
