-- TABLE_SCHEMA: S TABLE_NAME: P COLUMN_NAME: my id CONSTRAINT_SCHEMA: S CONSTRAINT_NAME: P_NOT_NULL_1

-- # Each constraint is in TABLE_CONSTRAINTS.
CREATE TABLE t (id INT PRIMARY KEY, c INT UNIQUE CHECK (c > 0));
SELECT DISTINCT ccu.constraint_name, tc.constraint_type FROM information_schema.constraint_column_usage AS ccu JOIN information_schema.table_constraints AS tc ON tc.constraint_name = ccu.constraint_name;
