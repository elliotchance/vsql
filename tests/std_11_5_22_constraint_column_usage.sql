-- # Each column that a constraint uses, in the same order as TABLE_CONSTRAINTS.
-- # A FOREIGN KEY uses the columns of the unique constraint that it references
-- # (in the referenced table), not its own columns. A CHECK uses the columns
-- # in its condition, in the order of the table.
CREATE TABLE parent (id INT PRIMARY KEY, a INT, b INT, UNIQUE (b, a));
CREATE TABLE child (x INT NOT NULL, y INT, z INT, CHECK (z > y AND x < z), FOREIGN KEY (x, y) REFERENCES parent (a, b), FOREIGN KEY (z) REFERENCES parent);
SELECT * FROM information_schema.constraint_column_usage;
