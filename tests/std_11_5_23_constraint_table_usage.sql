-- # The table that each PRIMARY KEY, UNIQUE and FOREIGN KEY uses, in the same
-- # order as TABLE_CONSTRAINTS. A FOREIGN KEY uses the table that it
-- # references, not its own table. A check constraint can't have a subquery, so
-- # it doesn't use a table.
CREATE TABLE parent (id INT PRIMARY KEY, a INT UNIQUE);
CREATE SCHEMA s;
CREATE TABLE s.child (x INT NOT NULL REFERENCES parent, y INT REFERENCES parent (a) CHECK (y > 0));
CREATE TABLE z (x INT CHECK (x > 0));
SELECT * FROM information_schema.constraint_table_usage;
