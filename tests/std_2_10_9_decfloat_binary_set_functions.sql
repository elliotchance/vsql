-- # The binary set functions are a DECFLOAT if either argument is one, with the
-- # larger precision (Syntax Rules, 9.c.ii.1), except REGR_COUNT, which counts
-- # rows. The other argument is cast to a DECFLOAT.
/* setup */
CREATE TABLE p (g INT, y DECFLOAT(16), x INT, z DECFLOAT);
INSERT INTO p VALUES (1, 1, 1, 1), (1, 3, 2, 2), (1, 2, 3, 3), (1, 5, 4, 4), (2, 7, 1, 1), (2, NULL, 2, 2), (3, 4, 5, 5), (4, NULL, NULL, NULL);

/* types */
SELECT g, REGR_COUNT(y, x), REGR_SXX(y, x), REGR_SYY(y, x), REGR_SXY(y, x), REGR_AVGX(y, x), REGR_AVGY(y, x) FROM p GROUP BY g;
