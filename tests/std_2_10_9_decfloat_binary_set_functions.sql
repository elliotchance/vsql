-- # CORR has the sign of the covariance. When every y is the same, REGR_R2 is
-- # 1, and CORR is NULL.
SELECT CORR(-y, x), REGR_R2(1, z), CORR(1, z) FROM p WHERE g = 1;
-- COL1: -0.8315218406202999 COL2: 1 COL3: NULL

-- # The sums are exact, so values that are large and close together don't
-- # lose their precision.
CREATE TABLE q (y DECFLOAT, x DECFLOAT);
INSERT INTO q VALUES (CAST('1E+30' AS DECFLOAT) + 1, 1), (CAST('1E+30' AS DECFLOAT) + 3, 2), (CAST('1E+30' AS DECFLOAT) + 5, 3);
SELECT REGR_SLOPE(y, x), REGR_INTERCEPT(y, x), REGR_SYY(y, x), CORR(y, x) FROM q;
-- msg: CREATE TABLE 1
-- msg: INSERT 3
-- COL1: 2 COL2: 999999999999999999999999999999 COL3: 8 COL4: 1

-- # A CORR, REGR_R2, REGR_SLOPE or REGR_INTERCEPT out of range is NULL, and any
-- # other is an error.
CREATE TABLE u (y DECFLOAT(16), x DECFLOAT(16));
INSERT INTO u VALUES (CAST('9E384' AS DECFLOAT(16)), CAST('1E-383' AS DECFLOAT(16))), (CAST('-9E384' AS DECFLOAT(16)), CAST('3E-383' AS DECFLOAT(16)));
SELECT REGR_SLOPE(y, x), REGR_INTERCEPT(y, x) FROM u;
SELECT REGR_SYY(y, x) FROM u;
