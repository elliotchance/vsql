-- # DROP IDENTITY needs F384 (Conformance Rules, 1), as well as F387 for ALTER
-- # COLUMN.
/* flags */
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY);
-- flags: T174
-- msg: CREATE TABLE 1

/* flags */
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
