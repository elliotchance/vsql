-- # DROP IDENTITY makes an identity column a normal column (General Rules, 2).
-- # The rows keep their values, and a value can then be inserted without
-- # OVERRIDING SYSTEM VALUE. The column is still NOT NULL, so a value has to be
-- # given.
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY, x INT);
INSERT INTO foo (x) VALUES (1), (2);
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
INSERT INTO foo (id, x) VALUES (10, 3);
INSERT INTO foo (x) VALUES (4);
SELECT * FROM foo;
SELECT IS_NULLABLE, IS_IDENTITY, IDENTITY_GENERATION, IDENTITY_START FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'FOO' AND COLUMN_NAME = 'ID';
-- msg: CREATE TABLE 1
-- msg: INSERT 2
-- msg: ALTER TABLE 1
-- msg: INSERT 1
-- error 23502: violates non-null constraint: column ID
-- ID: 1 X: 1
-- ID: 2 X: 2
-- ID: 10 X: 3
-- IS_NULLABLE: NO IS_IDENTITY: NO IDENTITY_GENERATION: NULL IDENTITY_START: NULL

-- # A GENERATED BY DEFAULT identity column, without the optional COLUMN. Its
-- # NOT NULL can be dropped once it isn't an identity column.
CREATE TABLE foo (id INT GENERATED BY DEFAULT AS IDENTITY, x INT);
INSERT INTO foo (x) VALUES (1);
ALTER TABLE foo ALTER id DROP IDENTITY;
ALTER TABLE foo DROP CONSTRAINT foo_not_null_1 RESTRICT;
INSERT INTO foo (x) VALUES (2);
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: ALTER TABLE 1
-- msg: ALTER TABLE 1
-- msg: INSERT 1
-- ID: 1 X: 1
-- ID: NULL X: 2

-- # Only an identity column has an identity to drop (11.12, Syntax Rules, 7).
CREATE TABLE foo (id INT);
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
-- msg: CREATE TABLE 1
-- error 42601: syntax error: column ID is not an identity column

CREATE TABLE foo (id INT GENERATED ALWAYS AS (1));
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
-- msg: CREATE TABLE 1
-- error 42601: syntax error: column ID is not an identity column

-- # The sequence is destroyed (General Rules, 3), so an identity column that's
-- # added later starts again.
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY (START WITH 5), x INT);
INSERT INTO foo (x) VALUES (1);
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
ALTER TABLE foo ADD COLUMN id2 INT GENERATED ALWAYS AS IDENTITY;
INSERT INTO foo (id, x) VALUES (6, 2);
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: ALTER TABLE 1
-- msg: ALTER TABLE 1
-- msg: INSERT 1
-- ID: 5 X: 1 ID2: 1
-- ID: 6 X: 2 ID2: 2

-- # A ROLLBACK brings back the identity and the current value of its sequence.
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY, x INT);
INSERT INTO foo (x) VALUES (1);
START TRANSACTION;
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
ROLLBACK;
INSERT INTO foo (x) VALUES (2);
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: START TRANSACTION
-- msg: ALTER TABLE 1
-- msg: ROLLBACK
-- msg: INSERT 1
-- ID: 1 X: 1
-- ID: 2 X: 2

-- # A dump has the column without its identity.
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY, x INT);
INSERT INTO foo (x) VALUES (1);
ALTER TABLE foo ALTER COLUMN id DROP IDENTITY;
/* out */
/* in */
SELECT * FROM foo;
