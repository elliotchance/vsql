-- # The table must exist (Syntax Rules, 2), so it can't be dropped twice, or
-- # be dropped from a schema that doesn't exist.
DROP TABLE foo RESTRICT;
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

CREATE TABLE foo (x FLOAT);
DROP TABLE foo RESTRICT;
DROP TABLE foo RESTRICT;
-- msg: CREATE TABLE 1
-- msg: DROP TABLE 1
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

DROP TABLE foo.bar RESTRICT;
-- error 3F000: invalid schema name: FOO

-- # A table in a schema other than PUBLIC.
CREATE SCHEMA foo;
CREATE TABLE foo.bar (baz BIGINT);
DROP TABLE foo.bar RESTRICT;
-- msg: CREATE SCHEMA 1
-- msg: CREATE TABLE 1
-- msg: DROP TABLE 1

-- # Dropping a table deletes its rows, so a new table with the same name is
-- # empty. The rows of a table whose name starts with the same name are kept.
CREATE TABLE foo (x INT);
INSERT INTO foo (x) VALUES (1);
INSERT INTO foo (x) VALUES (2);
DROP TABLE foo RESTRICT;
CREATE TABLE foo (x INT);
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: INSERT 1
-- msg: DROP TABLE 1
-- msg: CREATE TABLE 1

CREATE TABLE foo (x INT);
INSERT INTO foo (x) VALUES (1);
CREATE TABLE "FOO:BAR" (y INT);
INSERT INTO "FOO:BAR" (y) VALUES (2);
DROP TABLE foo RESTRICT;
SELECT * FROM "FOO:BAR";
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: DROP TABLE 1
-- Y: 2

-- # A table can't be used after it's dropped, by RESTRICT or CASCADE.
CREATE TABLE foo (x INT);
DROP TABLE foo RESTRICT;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: DROP TABLE 1
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

CREATE TABLE foo (x INT);
INSERT INTO foo (x) VALUES (1);
DROP TABLE foo CASCADE;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: DROP TABLE 1
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

-- # A FOREIGN KEY of the table itself doesn't stop RESTRICT.
CREATE TABLE foo (id INT PRIMARY KEY, parent INT REFERENCES foo);
INSERT INTO foo (id, parent) VALUES (1, NULL), (2, 1);
DROP TABLE foo RESTRICT;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 2
-- msg: DROP TABLE 1
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

-- # A table that was never created can't be dropped by either behavior.
DROP TABLE foo RESTRICT;
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

DROP TABLE foo CASCADE;
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

-- # DROP TABLE can't be used with EXPLAIN, and only one of RESTRICT or CASCADE
-- # can be given.
EXPLAIN DROP TABLE foo CASCADE;
-- error 42601: syntax error: Cannot EXPLAIN DROP TABLE

CREATE TABLE foo (x INT);
DROP TABLE foo RESTRICT CASCADE;
-- msg: CREATE TABLE 1
-- error 42601: syntax error: unexpected CASCADE at line 1, column 25 near "TABLE foo RESTRICT CASCADE"

-- # A table with an identity column is dropped outside of a transaction (#657),
-- # including for a connection that opens the file afterwards.
/* connection 1 */
CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY, x INT);
INSERT INTO t (x) VALUES (1);
DROP TABLE t RESTRICT;
SELECT * FROM t;
/* disconnect 1 */
/* connection 2 */
SELECT * FROM t;
CREATE TABLE t (y INT);
-- 1: msg: CREATE TABLE 1
-- 1: msg: INSERT 1
-- 1: msg: DROP TABLE 1
-- 1: error 42P01: no such table: "test".PUBLIC.T
-- 2: error 42P01: no such table: "test".PUBLIC.T
-- 2: msg: CREATE TABLE 1
