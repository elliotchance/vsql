-- out:   "B" TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT LOCALTIMESTAMP(0),
-- out:   "C" INTEGER,
-- out:   "D" DOUBLE PRECISION GENERATED ALWAYS AS (t.c + public.t.id + "T"."C" + 1.e0),
-- out:   PRIMARY KEY ("ID")
-- out: );
-- out: CREATE TABLE "PUBLIC"."U" (
-- out:   "ID" INTEGER NOT NULL,
-- out:   "A" NUMERIC(5, 2) NOT NULL,
-- out:   "B" TIMESTAMP(0) WITHOUT TIME ZONE,
-- out:   "C" INTEGER,
-- out:   "D" DOUBLE PRECISION
-- out: );

-- # INCLUDING IDENTITY copies the identity column with the options of its
-- # sequence generator, and starts the new one from the START WITH, not from
-- # where the other table's is (Syntax Rules, 9.b.iv.5). INCLUDING DEFAULTS
-- # copies the defaults (Syntax Rules, 9.b.iv.7), and INCLUDING GENERATED the
-- # generation expressions, which use the columns of the new table (Syntax
-- # Rules, 9.b.iv.6).
INSERT INTO t (c) VALUES (1), (2);
CREATE TABLE u (LIKE t INCLUDING IDENTITY INCLUDING DEFAULTS INCLUDING GENERATED);
INSERT INTO u (c) VALUES (3);
SELECT id, a, c, d FROM u;
