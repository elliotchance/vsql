-- # The options can be in any order, and only the ones that are given are
-- # included.
CREATE TABLE u (LIKE t INCLUDING GENERATED EXCLUDING IDENTITY);
INSERT INTO u (id, a, c) VALUES (1, 2, 3);
SELECT * FROM u;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- ID: 1 A: 2.00 B: NULL C: 3 D: 8e0

-- # The new table can be in another schema.
CREATE SCHEMA s;
CREATE TABLE s.u (LIKE t INCLUDING GENERATED);
INSERT INTO s.u (id, a, c) VALUES (1, 2, 3);
SELECT d FROM s.u;
-- msg: CREATE SCHEMA 1
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- D: 8e0

-- # Each option can only be given once (Syntax Rules, 9.b.iv.1).
CREATE TABLE u (LIKE t INCLUDING IDENTITY EXCLUDING IDENTITY);
-- error 42601: syntax error: LIKE T has more than one IDENTITY option

CREATE TABLE u (LIKE t INCLUDING DEFAULTS INCLUDING DEFAULTS);
-- error 42601: syntax error: LIKE T has more than one DEFAULTS option

CREATE TABLE u (LIKE t EXCLUDING GENERATED INCLUDING GENERATED);
-- error 42601: syntax error: LIKE T has more than one GENERATED option

-- # A view can't have options (Syntax Rules, 9.b.ii).
CREATE TABLE u (LIKE information_schema.schemata INCLUDING DEFAULTS);
-- error 42601: syntax error: LIKE INFORMATION_SCHEMA.SCHEMATA cannot have options, because it is a view

-- # <like options> are flagged with T173.
/* flags */
CREATE TABLE u (LIKE t INCLUDING DEFAULTS);
-- flags: T171, T173
-- msg: CREATE TABLE 1

-- # A table made by an <as subquery clause> from a table with defaults has no
-- # defaults, so INCLUDING DEFAULTS of it copies none.
CREATE TABLE u (LIKE t INCLUDING DEFAULTS);
INSERT INTO u (id, c) VALUES (1, 1);
SELECT a FROM u;
CREATE TABLE v AS (SELECT a FROM u) WITH NO DATA;
CREATE TABLE w (LIKE v INCLUDING DEFAULTS, e INT DEFAULT 7);
INSERT INTO w (a) VALUES (2.5);
SELECT * FROM w;
INSERT INTO w (e) VALUES (1);
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- A: 1.50
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- A: 2.50 E: 7
-- error 23502: violates non-null constraint: column A
