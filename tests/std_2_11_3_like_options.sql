/* setup */
CREATE TABLE t (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5 MAXVALUE 100 CYCLE) PRIMARY KEY,
  a NUMERIC(5, 2) DEFAULT 1.5 NOT NULL,
  b TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0),
  c INT,
  d DOUBLE PRECISION GENERATED ALWAYS AS (t.c + public.t.id + "T"."C" + 1.e0)
);

-- # Without <like options> (or with EXCLUDING), only the name, type and
-- # nullability of each column is copied (11.3, Syntax Rules, 9.b.iv.2, 9.b.iv.3
-- # and 9.b.iv.4).
CREATE TABLE u (LIKE t EXCLUDING IDENTITY EXCLUDING DEFAULTS EXCLUDING GENERATED);
/* out */
