-- # Without a MAXVALUE, the limit is the largest value of the type.
CREATE SEQUENCE s AS SMALLINT START WITH 32767;
SELECT NEXT VALUE FOR s FROM (VALUES 1) AS x;
SELECT NEXT VALUE FOR s FROM (VALUES 1) AS x;
