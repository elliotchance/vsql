-- # DEFAULT VALUES inserts one row where each column gets its default (Syntax
-- # Rules, 6). A column without a DEFAULT clause is NULL.
CREATE TABLE foo (x INT DEFAULT 123, y VARCHAR(10) DEFAULT 'hi', z INT);
INSERT INTO foo DEFAULT VALUES;
INSERT INTO foo DEFAULT VALUES;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: INSERT 1
-- X: 123 Y: hi Z: NULL
-- X: 123 Y: hi Z: NULL

-- # Each row is numbered by an identity column, even GENERATED ALWAYS, and a
-- # generated column is set from the defaults of the other columns.
CREATE TABLE foo (id INT GENERATED ALWAYS AS IDENTITY, x INT DEFAULT 5, y INT GENERATED ALWAYS AS (x * 2));
INSERT INTO foo DEFAULT VALUES;
INSERT INTO foo DEFAULT VALUES;
INSERT INTO foo (x) VALUES (7);
INSERT INTO foo DEFAULT VALUES;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: INSERT 1
-- msg: INSERT 1
-- msg: INSERT 1
-- ID: 1 X: 5 Y: 10
-- ID: 2 X: 5 Y: 10
-- ID: 3 X: 7 Y: 14
-- ID: 4 X: 5 Y: 10

CREATE TABLE foo (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5));
INSERT INTO foo DEFAULT VALUES;
INSERT INTO foo DEFAULT VALUES;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- msg: INSERT 1
-- ID: 10
-- ID: 15

-- # A NOT NULL column without a default is NULL, so no row is inserted.
CREATE TABLE foo (x INT DEFAULT 1, y INT NOT NULL);
INSERT INTO foo DEFAULT VALUES;
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- error 23502: violates non-null constraint: column Y

-- # The row must satisfy the constraints of the table.
CREATE TABLE foo (x INT DEFAULT 0 CHECK (x > 0));
INSERT INTO foo DEFAULT VALUES;
-- msg: CREATE TABLE 1
-- error 23514: violates check constraint: CHECK (X > 0) on ":memory:".PUBLIC.FOO

CREATE TABLE foo (x INT DEFAULT 1 PRIMARY KEY);
INSERT INTO foo DEFAULT VALUES;
INSERT INTO foo DEFAULT VALUES;
