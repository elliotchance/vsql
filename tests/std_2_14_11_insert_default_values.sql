-- # A table where every column is generated can only get rows from DEFAULT
-- # VALUES, and so they're dumped that way.
CREATE TABLE foo (x INT GENERATED ALWAYS AS (1));
INSERT INTO foo DEFAULT VALUES;
/* out */
/* in */
SELECT * FROM foo;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- out: CREATE TABLE "PUBLIC"."FOO" (
-- out:   "X" INTEGER GENERATED ALWAYS AS (1)
-- out: );
-- out: INSERT INTO "PUBLIC"."FOO" DEFAULT VALUES;
-- X: 1
