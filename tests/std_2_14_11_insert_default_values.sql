CREATE TABLE parent (id INT PRIMARY KEY);
CREATE TABLE child (parent_id INT DEFAULT 1 REFERENCES parent (id));
INSERT INTO child DEFAULT VALUES;
INSERT INTO parent (id) VALUES (1);
INSERT INTO child DEFAULT VALUES;
SELECT * FROM child;
-- msg: CREATE TABLE 1
-- msg: CREATE TABLE 1
-- error 23503: violates foreign key constraint: FOREIGN KEY (PARENT_ID) REFERENCES ":memory:".PUBLIC.PARENT (ID) on ":memory:".PUBLIC.CHILD
-- msg: INSERT 1
-- msg: INSERT 1
-- PARENT_ID: 1

-- # The table must exist.
INSERT INTO foo DEFAULT VALUES;
-- error 42P01: no such table: ":memory:".PUBLIC.FOO

