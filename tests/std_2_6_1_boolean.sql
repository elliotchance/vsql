-- # AND and OR use three-valued logic (6.39, General Rules, 3): FALSE AND
-- # anything is FALSE, TRUE OR anything is TRUE, and otherwise an UNKNOWN
-- # operand makes the result UNKNOWN.
VALUES TRUE AND TRUE;
-- COL1: TRUE

VALUES FALSE AND TRUE;
-- COL1: FALSE

VALUES UNKNOWN AND TRUE;
-- COL1: UNKNOWN

VALUES TRUE AND FALSE;
-- COL1: FALSE

VALUES FALSE AND FALSE;
-- COL1: FALSE

VALUES UNKNOWN AND FALSE;
-- COL1: FALSE

VALUES TRUE AND UNKNOWN;
-- COL1: UNKNOWN

VALUES FALSE AND UNKNOWN;
-- COL1: FALSE

/* types */
VALUES UNKNOWN AND UNKNOWN;
-- COL1: UNKNOWN (BOOLEAN)

VALUES TRUE OR TRUE;
-- COL1: TRUE

VALUES FALSE OR TRUE;
