-- # NOT swaps TRUE and FALSE, but NOT UNKNOWN is still UNKNOWN (6.39, General
-- # Rules, 2).
VALUES NOT TRUE;
-- COL1: FALSE

VALUES NOT FALSE;
-- COL1: TRUE

/* types */
VALUES NOT UNKNOWN;
