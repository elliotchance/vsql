-- # A string is trimmed, then read as a timestamp (6.13, General Rules,
-- # 18.a.ii).
/* types */
VALUES CAST('2022-06-30 12:34:56' AS TIMESTAMP(6));
-- COL1: 2022-06-30T12:34:56.000000 (TIMESTAMP(6) WITHOUT TIME ZONE)

-- # The time zone is dropped, keeping the local time.
VALUES CAST(' 2022-06-30 12:34:56+03:00 ' AS TIMESTAMP(0));
-- COL1: 2022-06-30T12:34:56

-- # The session time zone is added.
VALUES CAST('2022-06-30 12:34:56' AS TIMESTAMP WITH TIME ZONE);
-- COL1: 2022-06-30T12:34:56.000000+0500

-- # A string with a time zone keeps it. A string without a time, or with an
-- # invalid date, is an invalid datetime format (6.13, General Rules,
-- # 18.a.ii.3).
/* types */
VALUES CAST('2022-06-30 12:34:56.5+03:00' AS TIMESTAMP(3) WITH TIME ZONE);
-- COL1: 2022-06-30T12:34:56.500+0300 (TIMESTAMP(3) WITH TIME ZONE)

VALUES CAST('2022-06-30' AS TIMESTAMP);
-- error 22007: invalid datetime format

VALUES CAST('2022-13-01 12:34:56' AS TIMESTAMP);
-- error 22007: invalid datetime format

-- # A timestamp literal is also accepted, but the keyword must be TIMESTAMP.
VALUES CAST('TIMESTAMP ''2022-06-30 12:34:56''' AS TIMESTAMP(0));
-- COL1: 2022-06-30T12:34:56

VALUES CAST(CAST(TIMESTAMP '2022-06-30 12:34:56.5+03:00' AS VARCHAR(40)) AS TIMESTAMP(1) WITH TIME ZONE);
-- COL1: 2022-06-30T12:34:56.5+0300

VALUES CAST('DATE ''2022-06-30''' AS TIMESTAMP);
-- error 22007: invalid datetime format

-- # A TIMESTAMP without a precision is a TIMESTAMP(6) (Syntax Rules, 36).
/* types */
VALUES CAST(TIMESTAMP '2022-06-30 12:34:56' AS TIMESTAMP);
-- COL1: 2022-06-30T12:34:56.000000 (TIMESTAMP(6) WITHOUT TIME ZONE)

/* types */
VALUES CAST(TIMESTAMP '2022-06-30 12:34:56+05:00' AS TIMESTAMP WITH TIME ZONE);
-- COL1: 2022-06-30T12:34:56.000000+0500 (TIMESTAMP(6) WITH TIME ZONE)

CREATE TABLE foo (f1 TIMESTAMP);
INSERT INTO foo (f1) VALUES (TIMESTAMP '2022-06-30 21:47:32.123456');
SELECT * FROM foo;
