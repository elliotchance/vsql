-- # EXTRACT returns one field of a datetime (General Rules, 4.a). A DATE has
-- # YEAR, MONTH and DAY, a TIME has HOUR, MINUTE and SECOND, and a TIMESTAMP
-- # has all six (Syntax Rules, 6.a). Every field except SECOND is an INTEGER
-- # (Syntax Rules, 7.a).
/* types */
VALUES ROW(EXTRACT(YEAR FROM DATE '2026-11-14'), EXTRACT(MONTH FROM DATE '2026-11-14'), EXTRACT(DAY FROM DATE '2026-11-04'));
-- COL1: 2026 (INTEGER) COL2: 11 (INTEGER) COL3: 4 (INTEGER)

/* types */
VALUES ROW(EXTRACT(HOUR FROM TIME '01:02:03'), EXTRACT(MINUTE FROM TIME '01:02:03'));
-- COL1: 1 (INTEGER) COL2: 2 (INTEGER)

VALUES ROW(EXTRACT(YEAR FROM TIMESTAMP '0001-02-03 04:05:06'), EXTRACT(MONTH FROM TIMESTAMP '0001-02-03 04:05:06'), EXTRACT(DAY FROM TIMESTAMP '0001-02-03 04:05:06'), EXTRACT(HOUR FROM TIMESTAMP '0001-02-03 04:05:06'), EXTRACT(MINUTE FROM TIMESTAMP '0001-02-03 04:05:06'), EXTRACT(SECOND FROM TIMESTAMP '0001-02-03 04:05:06'));
-- COL1: 1 COL2: 2 COL3: 3 COL4: 4 COL5: 5 COL6: 6

-- # The fields are the local date and time of a value with a time zone, not
-- # the UTC ones.
VALUES ROW(EXTRACT(DAY FROM TIMESTAMP '2026-11-14 23:30:00-05:00'), EXTRACT(HOUR FROM TIME '23:30:00-05:00'));
-- COL1: 14 COL2: 23

-- # SECOND is a NUMERIC whose scale is the fractional seconds precision of the
-- # source (Syntax Rules, 7.b), so the fraction isn't lost.
/* types */
VALUES ROW(EXTRACT(SECOND FROM TIME '12:34:56'), EXTRACT(SECOND FROM TIME '12:34:05.120'), EXTRACT(SECOND FROM TIMESTAMP '2026-01-02 03:04:05.123456+01:00'));
-- COL1: 56 (NUMERIC(2)) COL2: 5.120 (NUMERIC(5, 3)) COL3: 5.123456 (NUMERIC(8, 6))

/* types */
VALUES EXTRACT(SECOND FROM CAST(TIME '12:34:05.987' AS TIME(1)));
-- COL1: 5.9 (NUMERIC(3, 1))

-- # TIMEZONE_HOUR and TIMEZONE_MINUTE are the time zone displacement, with its
-- # sign (General Rules, 4.b).
/* types */
VALUES ROW(EXTRACT(TIMEZONE_HOUR FROM TIME '12:00:00+05:45'), EXTRACT(TIMEZONE_MINUTE FROM TIME '12:00:00+05:45'));
-- COL1: 5 (INTEGER) COL2: 45 (INTEGER)

VALUES ROW(EXTRACT(TIMEZONE_HOUR FROM TIMESTAMP '2026-01-02 03:04:05-05:30'), EXTRACT(TIMEZONE_MINUTE FROM TIMESTAMP '2026-01-02 03:04:05-05:30'));
-- COL1: -5 COL2: -30

VALUES ROW(EXTRACT(TIMEZONE_HOUR FROM TIMESTAMP '2026-01-02 03:04:05-00:30'), EXTRACT(TIMEZONE_MINUTE FROM TIMESTAMP '2026-01-02 03:04:05-00:30'));
-- COL1: 0 COL2: -30

-- # The field must be one of the source (Syntax Rules, 6.a), and only a TIME or
-- # TIMESTAMP WITH TIME ZONE has a time zone (Syntax Rules, 6.b).
VALUES EXTRACT(HOUR FROM DATE '2026-11-14');
-- error 42804: data type mismatch in EXTRACT(HOUR FROM ...): expected TIME or TIMESTAMP but got DATE

VALUES EXTRACT(DAY FROM TIME '12:00:00');
-- error 42804: data type mismatch in EXTRACT(DAY FROM ...): expected DATE or TIMESTAMP but got TIME(0) WITHOUT TIME ZONE

VALUES EXTRACT(TIMEZONE_HOUR FROM TIMESTAMP '2026-01-02 03:04:05');
-- error 42804: data type mismatch in EXTRACT(TIMEZONE_HOUR FROM ...): expected TIME WITH TIME ZONE or TIMESTAMP WITH TIME ZONE but got TIMESTAMP(0) WITHOUT TIME ZONE

-- # There are no intervals (F052), so the source must be a datetime.
VALUES EXTRACT(YEAR FROM 2026);
-- error 42804: data type mismatch in EXTRACT(YEAR FROM ...): expected DATE or TIMESTAMP but got SMALLINT

VALUES EXTRACT(FORTNIGHT FROM DATE '2026-11-14');
-- error 42601: syntax error: EXTRACT has no field FORTNIGHT

-- # EXTRACT of a NULL is NULL.
/* types */
VALUES ROW(EXTRACT(YEAR FROM CAST(NULL AS DATE)), EXTRACT(SECOND FROM CAST(NULL AS TIME(2))));
-- COL1: NULL (INTEGER) COL2: NULL (NUMERIC(4, 2))

-- # It's a numeric value, so it can be used in arithmetic, and on columns.
/* setup */
CREATE TABLE t (d TIMESTAMP(3) WITH TIME ZONE CHECK (EXTRACT(YEAR FROM d) > 2000));
INSERT INTO t (d) VALUES (TIMESTAMP '2026-01-02 03:04:05.5+01:00'), (TIMESTAMP '2027-06-02 03:04:05.25-02:00');

VALUES -EXTRACT(YEAR FROM DATE '2026-11-14') + 1;
-- COL1: -2025

SELECT EXTRACT(YEAR FROM d) AS y, EXTRACT(SECOND FROM d) AS s, EXTRACT(TIMEZONE_HOUR FROM d) AS tz FROM t WHERE EXTRACT(MONTH FROM d) > 1;
-- Y: 2027 S: 5.250 TZ: -2

INSERT INTO t (d) VALUES (TIMESTAMP '1999-01-02 03:04:05+01:00');
