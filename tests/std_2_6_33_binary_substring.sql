-- # A <binary substring function> counts octets. Its type is a BINARY VARYING
-- # with the length of the value, or a BINARY LARGE OBJECT of the same maximum
-- # length for one (6.33, Syntax Rules, 21).
/* types */
VALUES SUBSTRING(X'0102030405' FROM 2);
-- COL1: 02030405 (BINARY VARYING(5))

/* types */
VALUES SUBSTRING(X'0102030405' FROM 2 FOR 3);
-- COL1: 020304 (BINARY VARYING(5))

/* types */
CREATE TABLE t (a BINARY(4), b VARBINARY(6), c BLOB(8), d BLOB);
INSERT INTO t VALUES (X'01020304', X'0A0B0C', X'FFEE', X'00');
SELECT SUBSTRING(a FROM 3), SUBSTRING(b FROM 1 FOR 2), SUBSTRING(c FROM 2), SUBSTRING(d FROM 1) FROM t;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- COL1: 0304 (BINARY VARYING(4)) COL2: 0A0B (BINARY VARYING(6)) COL3: EE (BINARY LARGE OBJECT(8)) COL4: 00 (BINARY LARGE OBJECT)

-- # A start before the value or past its end is like SUBSTRING of a character
-- # string (6.33, General Rules, 17.e), and a negative length is an error
-- # (6.33, General Rules, 17.d).
VALUES SUBSTRING(X'0102030405' FROM 0 FOR 3);
VALUES SUBSTRING(X'0102030405' FROM -5 FOR 3);
VALUES SUBSTRING(X'0102030405' FROM 6);
VALUES SUBSTRING(X'0102030405' FROM 3 FOR 100);
VALUES SUBSTRING(X'0102030405' FROM 3 FOR -1);
-- COL1: 0102
-- COL1:
-- COL1:
-- COL1: 030405
-- error 22011: substring error

-- # The result is NULL if any argument is NULL (6.33, General Rules, 17.c).
/* types */
CREATE TABLE t (a VARBINARY(3), n INT);
INSERT INTO t VALUES (NULL, NULL);
SELECT SUBSTRING(a FROM 1), SUBSTRING(X'01' FROM n), SUBSTRING(X'01' FROM 1 FOR n) FROM t;
-- msg: CREATE TABLE 1
-- msg: INSERT 1
-- COL1: NULL (BINARY VARYING(3)) COL2: NULL (BINARY VARYING(1)) COL3: NULL (BINARY VARYING(1))

-- # A binary string doesn't have characters, so it can't have USING.
VALUES SUBSTRING(X'0102' FROM 1 USING OCTETS);
-- error 42601: syntax error: SUBSTRING of BINARY(2) cannot have USING OCTETS

