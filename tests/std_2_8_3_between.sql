-- # Both bounds are inclusive. Without SYMMETRIC (ASYMMETRIC is the default,
-- # SR 1), the lower bound must come first or nothing is between them. NOT
-- # BETWEEN is the opposite (SR 3 and 5).
VALUES 35 BETWEEN 30 AND 40;
-- COL1: TRUE

VALUES 35 BETWEEN 35 AND 40;
-- COL1: TRUE

VALUES 40 BETWEEN 35 AND 40;
-- COL1: TRUE

VALUES 34 BETWEEN 35 AND 40;
-- COL1: FALSE

VALUES 41 BETWEEN 35 AND 40;
-- COL1: FALSE

VALUES 35 BETWEEN 40 AND 30;
-- COL1: FALSE

VALUES 35 BETWEEN ASYMMETRIC 40 AND 30;
-- COL1: FALSE

VALUES 35 BETWEEN SYMMETRIC 40 AND 30;
-- COL1: TRUE

VALUES 35 NOT BETWEEN 30 AND 40;
-- COL1: FALSE

VALUES 35 NOT BETWEEN 35 AND 40;
-- COL1: FALSE

VALUES 40 NOT BETWEEN 35 AND 40;
-- COL1: FALSE

VALUES 34 NOT BETWEEN 35 AND 40;
-- COL1: TRUE

VALUES 41 NOT BETWEEN 35 AND 40;
-- COL1: TRUE

VALUES 35 NOT BETWEEN 40 AND 30;
-- COL1: TRUE

-- # X BETWEEN Y AND Z is X >= Y AND X <= Z (SR 6), so a NULL bound only makes
-- # it UNKNOWN when the other bound doesn't already make it FALSE. SYMMETRIC
-- # tries the bounds both ways around with OR (SR 4).
/* setup */
CREATE TABLE t (x INT);
INSERT INTO t (x) VALUES (NULL);
INSERT INTO t (x) VALUES (3);
CREATE TABLE n (x INT);
INSERT INTO n (x) VALUES (NULL);

SELECT x, 5 BETWEEN x AND 2, 5 NOT BETWEEN x AND 2 FROM t;
-- X: NULL COL2: FALSE COL3: TRUE
-- X: 3 COL2: FALSE COL3: TRUE

SELECT x FROM t WHERE 5 NOT BETWEEN x AND 2;
-- X: NULL
-- X: 3

-- # A bound can be an aggregate function.
SELECT 2 BETWEEN 0 AND COUNT(*) FROM t;
-- COL1: TRUE

SELECT 5 BETWEEN x AND 2 FROM n;
-- COL1: FALSE

SELECT 5 NOT BETWEEN x AND 2 FROM n;
-- COL1: TRUE

SELECT 5 BETWEEN x AND 10 FROM n;
-- COL1: UNKNOWN

SELECT 5 NOT BETWEEN x AND 10 FROM n;
-- COL1: UNKNOWN

SELECT 5 BETWEEN 10 AND x FROM n;
-- COL1: FALSE

SELECT 5 NOT BETWEEN 10 AND x FROM n;
-- COL1: TRUE

SELECT 5 BETWEEN 2 AND x FROM n;
-- COL1: UNKNOWN

SELECT x BETWEEN 2 AND 10 FROM n;
-- COL1: UNKNOWN

SELECT 5 BETWEEN x AND x FROM n;
-- COL1: UNKNOWN

SELECT 5 BETWEEN SYMMETRIC x AND 2 FROM n;
-- COL1: UNKNOWN

SELECT 5 NOT BETWEEN SYMMETRIC x AND 2 FROM n;
-- COL1: UNKNOWN

SELECT 5 BETWEEN SYMMETRIC 10 AND x FROM n;
-- COL1: UNKNOWN

-- # NOT BETWEEN with an explicit ASYMMETRIC or SYMMETRIC.
VALUES 35 NOT BETWEEN ASYMMETRIC 40 AND 30;
-- COL1: TRUE

VALUES 35 NOT BETWEEN SYMMETRIC 40 AND 30;
-- COL1: FALSE

-- # Bounds of other numeric types, and character strings, which are compared
-- # in the order of their characters.
VALUES 3.5 BETWEEN 3 AND 4.1;
-- COL1: TRUE

VALUES 3.5 BETWEEN 3.6 AND 4.1;
-- COL1: FALSE

VALUES 'hello' BETWEEN 'hella' AND 'hellr';
-- COL1: TRUE

VALUES 'h' BETWEEN 'x' AND 'y';
-- COL1: FALSE

VALUES 'h' BETWEEN 'ka' AND 'h';
-- COL1: FALSE

VALUES 'h' BETWEEN SYMMETRIC 'ka' AND 'h';
-- COL1: TRUE

VALUES 'i' BETWEEN 'h' AND 'j';
-- COL1: TRUE

