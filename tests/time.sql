INSERT INTO foo (f1) VALUES (TIME '21:47:32.123+02:00');
SELECT CAST(f1 AS TIMESTAMP(2) WITH TIME ZONE) FROM foo;
SELECT CAST(f1 AS TIMESTAMP(0) WITHOUT TIME ZONE) FROM foo;
