-- # More of PostgreSQL's EXTRACT fields (V402-13 to V402-19): JULIAN, CENTURY,
-- # DECADE, MILLENNIUM, MILLISECONDS, MICROSECONDS and TIMEZONE.

-- # JULIAN is the Julian Day Number, plus the fraction of the day since local
-- # midnight for a TIMESTAMP. A DATE is a whole number, and a TIMESTAMP has 12
-- # decimal places.
/* types */
/* extensions V402-13 */
VALUES ROW(EXTRACT(JULIAN FROM DATE '2026-11-17'), EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 00:00:00'), EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 12:00:00'));
-- COL1: 2461362 (NUMERIC(7)) COL2: 2461362.000000000000 (NUMERIC(19, 12)) COL3: 2461362.500000000000 (NUMERIC(19, 12))

/* extensions V402-13 */
VALUES ROW(EXTRACT(JULIAN FROM DATE '0001-01-01'), EXTRACT(JULIAN FROM DATE '1970-01-01'), EXTRACT(JULIAN FROM DATE '9999-12-31'));
-- COL1: 1721426 COL2: 2440588 COL3: 5373484

-- # The fraction is cut, not rounded, and tells microseconds apart.
/* extensions V402-13 */
VALUES ROW(EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 12:30:15'), EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 00:00:00.000001'), EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 01:00:00.000000'));
-- COL1: 2461362.521006944444 COL2: 2461362.000000000011 COL3: 2461362.041666666666

-- # A value WITH TIME ZONE uses its local date and time.
/* extensions V402-13 */
VALUES ROW(EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 12:00:00+10:30'), EXTRACT(JULIAN FROM TIMESTAMP '2026-11-17 12:00:00-05:00'));
-- COL1: 2461362.500000000000 COL2: 2461362.500000000000

-- # CENTURY and MILLENNIUM start in a year ending in 1, and there's no century
-- # or millennium 0.
/* types */
/* extensions V402-14 V402-16 */
VALUES ROW(EXTRACT(CENTURY FROM DATE '2026-11-17'), EXTRACT(MILLENNIUM FROM TIMESTAMP '2026-11-17 12:00:00'));
-- COL1: 21 (INTEGER) COL2: 3 (INTEGER)

/* extensions V402-14 V402-16 */
VALUES ROW(EXTRACT(CENTURY FROM DATE '0001-01-01'), EXTRACT(CENTURY FROM DATE '0100-12-31'), EXTRACT(CENTURY FROM DATE '0101-01-01'), EXTRACT(MILLENNIUM FROM DATE '0001-01-01'));
-- COL1: 1 COL2: 1 COL3: 2 COL4: 1

/* extensions V402-14 V402-16 */
VALUES ROW(EXTRACT(CENTURY FROM DATE '1000-06-01'), EXTRACT(CENTURY FROM DATE '1001-06-01'), EXTRACT(MILLENNIUM FROM DATE '1000-06-01'), EXTRACT(MILLENNIUM FROM DATE '1001-06-01'));
-- COL1: 10 COL2: 11 COL3: 1 COL4: 2

/* extensions V402-14 V402-16 */
VALUES ROW(EXTRACT(CENTURY FROM TIMESTAMP '2000-12-31 23:59:59'), EXTRACT(CENTURY FROM TIMESTAMP '2001-01-01 00:00:00'), EXTRACT(MILLENNIUM FROM DATE '2000-12-31'), EXTRACT(MILLENNIUM FROM DATE '2001-01-01'));
-- COL1: 20 COL2: 21 COL3: 2 COL4: 3

-- # DECADE is the year divided by 10.
/* types */
/* extensions V402-15 */
VALUES ROW(EXTRACT(DECADE FROM DATE '2026-11-17'), EXTRACT(DECADE FROM DATE '2020-01-01'), EXTRACT(DECADE FROM TIMESTAMP '2029-12-31 23:59:59+10:00'), EXTRACT(DECADE FROM DATE '0009-01-01'));
-- COL1: 202 (INTEGER) COL2: 202 (INTEGER) COL3: 202 (INTEGER) COL4: 0 (INTEGER)

-- # MILLISECONDS and MICROSECONDS are the whole SECOND field (not only its
-- # fraction) times 1000 and 1000000. MILLISECONDS is a NUMERIC that keeps the
-- # places of the precision after the first 3, and MICROSECONDS is an INTEGER.
/* types */
/* extensions V402-17 V402-18 */
VALUES ROW(EXTRACT(MILLISECONDS FROM TIME '12:30:12.5'), EXTRACT(MICROSECONDS FROM TIME '12:30:12.5'));
-- COL1: 12500 (NUMERIC(5)) COL2: 12500000 (INTEGER)

/* types */
/* extensions V402-17 V402-18 */
VALUES ROW(EXTRACT(MILLISECONDS FROM TIME '12:30:12'), EXTRACT(MICROSECONDS FROM TIMESTAMP '2026-11-17 12:30:12'));
-- COL1: 12000 (NUMERIC(5)) COL2: 12000000 (INTEGER)

/* types */
/* extensions V402-17 V402-18 */
VALUES ROW(EXTRACT(MILLISECONDS FROM TIME '12:30:12.123'), EXTRACT(MILLISECONDS FROM TIMESTAMP '2026-11-17 12:30:12.1234'), EXTRACT(MILLISECONDS FROM TIME '12:30:59.123456+05:00'), EXTRACT(MICROSECONDS FROM TIMESTAMP '2026-11-17 12:30:59.123456-05:00'));
-- COL1: 12123 (NUMERIC(5)) COL2: 12123.4 (NUMERIC(6, 1)) COL3: 59123.456 (NUMERIC(8, 3)) COL4: 59123456 (INTEGER)

/* extensions V402-17 V402-18 */
VALUES ROW(EXTRACT(MILLISECONDS FROM TIME '00:00:00.000001'), EXTRACT(MICROSECONDS FROM TIME '00:00:00.000001'), EXTRACT(MILLISECONDS FROM TIME '00:00:00.01'));
-- COL1: 0.001 COL2: 1 COL3: 10

-- # TIMEZONE is the time zone in seconds, with its sign. It's only for a value
-- # WITH TIME ZONE, and it's F411, like TIMEZONE_HOUR.
/* types */
/* extensions V402-19 */
VALUES ROW(EXTRACT(TIMEZONE FROM TIME '12:00:00+10:30'), EXTRACT(TIMEZONE FROM TIMESTAMP '2026-11-17 12:00:00-05:00'), EXTRACT(TIMEZONE FROM TIME '12:00:00-03:30'), EXTRACT(TIMEZONE FROM TIME '12:00:00+00:00'));
-- COL1: 37800 (INTEGER) COL2: -18000 (INTEGER) COL3: -12600 (INTEGER) COL4: 0 (INTEGER)

-- # A field that the type doesn't have is an error.
/* extensions V402-13 */
VALUES EXTRACT(JULIAN FROM TIME '12:00:00');
-- error 42804: data type mismatch in EXTRACT(JULIAN FROM ...): expected DATE or TIMESTAMP but got TIME(0) WITHOUT TIME ZONE

/* extensions V402-14 */
VALUES EXTRACT(CENTURY FROM TIME '12:00:00');
-- error 42804: data type mismatch in EXTRACT(CENTURY FROM ...): expected DATE or TIMESTAMP but got TIME(0) WITHOUT TIME ZONE

/* extensions V402-15 */
VALUES EXTRACT(DECADE FROM TIME '12:00:00+01:00');
-- error 42804: data type mismatch in EXTRACT(DECADE FROM ...): expected DATE or TIMESTAMP but got TIME(0) WITH TIME ZONE

/* extensions V402-16 */
VALUES EXTRACT(MILLENNIUM FROM INTERVAL '10' YEAR);
-- error 42804: data type mismatch in EXTRACT(MILLENNIUM FROM ...): expected DATE or TIMESTAMP but got INTERVAL YEAR(2)

/* extensions V402-17 */
VALUES EXTRACT(MILLISECONDS FROM DATE '2026-11-17');
-- error 42804: data type mismatch in EXTRACT(MILLISECONDS FROM ...): expected TIME or TIMESTAMP but got DATE

/* extensions V402-18 */
VALUES EXTRACT(MICROSECONDS FROM DATE '2026-11-17');
-- error 42804: data type mismatch in EXTRACT(MICROSECONDS FROM ...): expected TIME or TIMESTAMP but got DATE

/* extensions V402-19 */
VALUES EXTRACT(TIMEZONE FROM TIMESTAMP '2026-11-17 12:00:00');
-- error 42804: data type mismatch in EXTRACT(TIMEZONE FROM ...): expected TIME WITH TIME ZONE or TIMESTAMP WITH TIME ZONE but got TIMESTAMP(0) WITHOUT TIME ZONE

/* extensions V402-19 */
VALUES EXTRACT(TIMEZONE FROM DATE '2026-11-17');
-- error 42804: data type mismatch in EXTRACT(TIMEZONE FROM ...): expected TIME WITH TIME ZONE or TIMESTAMP WITH TIME ZONE but got DATE

-- # EXTRACT of a NULL is NULL.
/* types */
/* extensions V402-13 V402-14 V402-17 V402-18 V402-19 */
VALUES ROW(EXTRACT(JULIAN FROM CAST(NULL AS DATE)), EXTRACT(JULIAN FROM CAST(NULL AS TIMESTAMP)), EXTRACT(CENTURY FROM CAST(NULL AS DATE)), EXTRACT(MILLISECONDS FROM CAST(NULL AS TIME(6))), EXTRACT(MICROSECONDS FROM CAST(NULL AS TIME)), EXTRACT(TIMEZONE FROM CAST(NULL AS TIME WITH TIME ZONE)));
-- COL1: NULL (NUMERIC(7)) COL2: NULL (NUMERIC(19, 12)) COL3: NULL (INTEGER) COL4: NULL (NUMERIC(8, 3)) COL5: NULL (INTEGER) COL6: NULL (INTEGER)

-- # The fields aren't keywords, so they can be in any case.
/* extensions V402-14 V402-17 */
values row(extract(century from date '2026-11-17'), extract(Milliseconds from time '12:30:12.5'));
-- COL1: 21 COL2: 12500

-- # The flagger reports each field (see docs/sql-flagging.rst). F641 and F661
-- # are for VALUES, T051 is for ROW, F411 is for TIMEZONE and F555
-- # is for the fractional seconds.
/* flags */
/* extensions V402-13 V402-14 V402-15 V402-16 */
VALUES ROW(EXTRACT(JULIAN FROM DATE '2026-11-17'), EXTRACT(CENTURY FROM DATE '2026-11-17'), EXTRACT(DECADE FROM DATE '2026-11-17'), EXTRACT(MILLENNIUM FROM DATE '2026-11-17'));
-- flags: F052, F641, F661, T051, V402-13, V402-14, V402-15, V402-16
-- COL1: 2461362 COL2: 21 COL3: 202 COL4: 3

/* flags */
/* extensions V402-17 V402-18 V402-19 */
VALUES ROW(EXTRACT(MILLISECONDS FROM TIME '12:30:12.5+10:30'), EXTRACT(MICROSECONDS FROM TIME '12:30:12.5'), EXTRACT(TIMEZONE FROM TIME '12:30:12+10:30'));
-- flags: F052, F411, F555, F641, F661, T051, V402-17, V402-18, V402-19
-- COL1: 12500 COL2: 12500000 COL3: 37800
