module vsql

// A catalog that is added during a transaction joins it, so a ROLLBACK also
// undoes the changes made to it.
fn test_catalog_added_during_transaction() ! {
	mut db := open(':memory:')!
	db.query('START TRANSACTION')!
	db.add_catalog('FOO', ':memory:', default_connection_options())!
	db.query('CREATE TABLE foo.public.bar (baz INTEGER)')!
	db.query('ROLLBACK')!

	db.query('SELECT * FROM foo.public.bar') or {
		assert err.msg() == 'no such table: FOO.PUBLIC.BAR'
		return
	}
	assert false
}

// An isolation block inside another one (such as the identity value when
// dropping a table, or NEXT VALUE FOR) is part of the same implicit
// transaction, so no transaction is left active after each statement (#657).
fn test_no_active_transactions_after_autocommit() ! {
	mut db := open(':memory:')!
	db.query('CREATE SEQUENCE s')!
	db.query('CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY, x INT)')!
	db.query('INSERT INTO t (x) VALUES (NEXT VALUE FOR s)')!
	db.query('DROP TABLE t')!

	catalog := db.catalogs[db.current_catalog] or { panic('no catalog') }
	for tid in catalog.storage.header.active_transaction_ids.tids {
		assert tid == 0
	}
}
