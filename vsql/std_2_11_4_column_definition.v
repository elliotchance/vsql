module vsql

// ISO/IEC 9075-2:2016(E), 11.4, <column definition>
//
// Define a column of a base table.

// A <column constraint>. NOT NULL is the only one that isn't added to the table
// as a table constraint, but it's also a table element when it has a name.
type ColumnConstraint = CheckConstraintDefinition
	| NotNullConstraint
	| ReferentialConstraintDefinition
	| UniqueConstraintDefinition

// The column of a NotNullConstraint is only set once it's a table element.
struct NotNullConstraint {
	name   Identifier
	column string
}

// add_column_constraint applies a <column constraint> to the column, which is
// the first of the elements. A PRIMARY KEY, UNIQUE, REFERENCES or CHECK on a
// column is the same as the table constraint, such as PRIMARY KEY (column) or
// FOREIGN KEY (column) REFERENCES ..., so it's added as one (Syntax Rule 17).
// It's checked with the other table elements, so it's also an error if the
// table has another PRIMARY KEY. A CHECK on a column can only use that column
// (Syntax Rule 17d).
fn add_column_constraint(elements []TableElement, constraint ColumnConstraint) []TableElement {
	column := elements[0] as Column
	match constraint {
		NotNullConstraint {
			mut new_elements := elements.clone()
			new_elements[0] = Column{
				...column
				not_null: true
			}
			if constraint.name.entity_name != '' {
				new_elements << NotNullConstraint{
					...constraint
					column: column.name.sub_entity_name
				}
			}
			return new_elements
		}
		UniqueConstraintDefinition {
			return append_list(elements, TableElement(UniqueConstraintDefinition{
				...constraint
				columns: [column.name]
			}))
		}
		ReferentialConstraintDefinition {
			return append_list(elements, TableElement(ReferentialConstraintDefinition{
				...constraint
				columns: [column.name]
			}))
		}
		CheckConstraintDefinition {
			return append_list(elements, TableElement(CheckConstraintDefinition{
				...constraint
				column_name: column.name.sub_entity_name
			}))
		}
	}
}

// IdentityColumn is an <identity column specification>: "GENERATED { ALWAYS |
// BY DEFAULT } AS IDENTITY", with the options of its internal sequence
// generator. Only the definition of the sequence is part of the column, its
// current value is stored separately (see Storage.identity_next_value).
struct IdentityColumn {
	// always is true for GENERATED ALWAYS, so that the column can only be
	// assigned DEFAULT. Otherwise, it's GENERATED BY DEFAULT.
	always  bool
	options []SequenceGeneratorOption
mut:
	// sequence is set from the options by new_identity_sequence.
	sequence Sequence
}

// str returns the SQL for the identity column, which is also how it's stored
// in the file as part of the CREATE TABLE, like:
//
//   GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647)
fn (i IdentityColumn) str() string {
	generated := if i.always { 'ALWAYS' } else { 'BY DEFAULT' }
	mut options := ['START WITH ${i.sequence.start_value}', 'INCREMENT BY ${i.sequence.increment_by}',
		'MINVALUE ${i.sequence.min_value}', 'MAXVALUE ${i.sequence.max_value}']
	if i.sequence.cycle {
		options << 'CYCLE'
	}

	return 'GENERATED ${generated} AS IDENTITY (${options.join(' ')})'
}

// exact_numeric_range is the smallest and largest value of an exact numeric
// type with a scale of 0 (zero), as far as they fit in a BIGINT.
fn exact_numeric_range(t Type) (i64, i64) {
	if t.typ == .is_smallint {
		return min_i16, max_i16
	}
	if t.typ == .is_integer {
		return min_i32, max_i32
	}
	if t.typ in [.is_decimal, .is_numeric] && t.size < 19 {
		mut max := i64(1)
		for _ in 0 .. t.size {
			max *= 10
		}
		return -(max - 1), max - 1
	}

	return min_i64, max_i64
}

// new_identity_sequence returns the internal sequence generator of an identity
// column (Syntax Rule 16). The column must be an exact numeric with a scale of
// 0 (zero), and the options must be representable by its type.
//
// A MINVALUE or MAXVALUE that isn't given is implementation-defined (9.30,
// Syntax Rules 7 and 8). Like PostgreSQL, it's 1 to the largest value of the
// type for an ascending sequence, and the smallest value of the type to -1 for
// a descending sequence. So the default START WITH is 1 or -1.
fn new_identity_sequence(column Column, options []SequenceGeneratorOption) !Sequence {
	if column.typ.typ !in [.is_smallint, .is_integer, .is_bigint, .is_decimal, .is_numeric]
		|| column.typ.scale != 0 {
		return sqlstate_42601('identity column ${column.name.sub_entity_name} must be an exact numeric with a scale of 0, not ${column.typ}')
	}

	check_sequence_options(options)!
	sequence := SequenceGeneratorDefinition{
		options: options
	}.sequence(column.name)
	min, max := identity_range(column.typ, sequence.increment_by)
	mut all_options := options.clone()
	if !sequence.has_min_value {
		all_options << SequenceGeneratorMinvalueOption{new_bigint_value(min)}
	}
	if !sequence.has_max_value {
		all_options << SequenceGeneratorMaxvalueOption{new_bigint_value(max)}
	}
	identity_sequence := SequenceGeneratorDefinition{
		options: all_options
	}.sequence(column.name)
	check_identity_sequence(column.typ, identity_sequence)!
	identity_sequence.check_in_range('START WITH', identity_sequence.start_value)!

	return identity_sequence
}

// identity_range is the default MINVALUE and MAXVALUE of the sequence of an
// identity column of type t (see new_identity_sequence).
fn identity_range(t Type, increment_by i64) (i64, i64) {
	min, max := exact_numeric_range(t)
	if increment_by > 0 {
		return 1, max
	}

	return min, -1
}

// check_identity_sequence returns an error if the sequence of an identity
// column of type t isn't valid (9.30, Syntax Rules 10 to 11).
fn check_identity_sequence(t Type, s Sequence) ! {
	min, max := exact_numeric_range(t)
	for name, value in {
		'INCREMENT BY': s.increment_by
		'MINVALUE':     s.min_value
		'MAXVALUE':     s.max_value
	} {
		if value < min || value > max {
			return sqlstate_42601('${name} (${value}) is out of range for ${t}')
		}
	}

	s.check()!
}
